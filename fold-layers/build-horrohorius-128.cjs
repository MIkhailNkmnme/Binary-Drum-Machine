/* Reproducible frozen central pyramid. Keep both checkerboard lattices. */
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const M=require('../mayatnik/mayatnik-core.js'),N=128,step=4*N;
const g=M.geometry('pend',step+2,N),f=M.field(g.W,N,'empty',g.anchor);
const rows=()=>Array.from({length:N},(_,r)=>Array.from(f.val.subarray(r*g.W+g.anchor-r,r*g.W+g.anchor+r+1)).join(''));
let previous;
for(let k=0;k<step;k++){if(k===step-1)previous=rows();M.cone(f,g.anchor+M.offset('pend',k),N);}
const stable=rows();assert.deepEqual(stable,previous,'All 128 rows must equal the preceding step');
// Any future cone's apex is farther than 2*(N-1); it cannot meet |x|<=r, r<N.
assert(Math.abs(M.offset('pend',step))>2*(N-1));assert(Math.abs(M.offset('pend',step+1))>2*(N-1));
for(let k=step;k<step+2;k++)M.cone(f,g.anchor+M.offset('pend',k),N);
assert.deepEqual(rows(),stable,'The next two cones must not change any source cell');
assert(stable.every((s,r)=>s.length===2*r+1&&/^[01]+$/.test(s)));
const data={meta:{name:'Хоррохориус · неизменяемая центральная пирамида',rows:N,step,previousStep:step-1,unchangedFromPrevious:true,coordinates:'row r=0..127, x=-r..r, both parities',bits:N*N},rows:stable};
fs.writeFileSync(path.join(__dirname,'horrohorius-128.js'),'/* Generated by build-horrohorius-128.cjs; verified with MAYATNIK. */\nwindow.ZZ_HORROHORIUS_128='+JSON.stringify(data)+';\n');
console.log(JSON.stringify({rows:N,bits:N*N,step,previousStep:step-1,first:stable.slice(0,6),lastWidth:stable.at(-1).length}));
