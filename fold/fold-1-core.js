var pat2Align = "left";   // П2 (правое поле) — зеркально, тоже к центру

function alignShift(maxLen, len, align, rowIdx){
  const diff = maxLen - len;
  const ri = rowIdx || 0;
  // "Ось"/"Ось 1.2" (⊙, data-val="axis"/"axis12") — базовое (СТАТИЧЕСКОЕ) значение: столбец
  // оси = maxLen/2 — середина ВИДИМОЙ области (между #vsplit и #vsplit2), см. подробный
  // комментарий у axisRowShift() выше (реальная сетка под "Ось" вдвое шире maxLen, но лишняя
  // половина — скрытый запас ВПРАВО, не часть видимой середины). Это лишь точка отсчёта по
  // умолчанию (когда строка ещё ни разу не сдвигалась) — РЕАЛЬНЫЙ сдвиг конкретной строки при
  // рендере, с учётом кругового сдвига ◄/►Круг(Инв), считает axisRowShift(). Эта функция
  // (alignShift) используется как обобщённая точка отсчёта там, где конкретная строка/её сдвиг
  // ещё не важны (Тетрис-Ось и т.п.).
  if (align === "axis" || align === "axis12") return Math.floor(maxLen / 2); // свой сдвиг оси — см. axisRowShift(), там свой же axisCenterOffset
  // ВАЖНО: сдвиг ручки #axisSplit (st.axisCenterOffset) СЮДА НЕ ВХОДИТ и входить не должен.
  // Раньше он прибавлялся здесь, к сдвигу каждой строки — и тем самым протекал в ДАННЫЕ, а не
  // только в картинку: alignShift() зовут не только render(), но и вертикальная склейка/XOR/
  // фон-поиск (concatVerticalDownTo, xorRowsDownTo, buildVerticalChain и т.п.). Там колонки
  // перебираются от 0, поэтому при сдвиге ВПРАВО первые offset колонок оказывались пустыми у
  // ВСЕХ строк разом, и галка "padZero" набивала в результат длинный хвост нулей (запрос
  // пользователя — "Xor в фоновом поиске откуда-то добавляет 000000 при перемещении вправо").
  // Плюс сдвиг ломал совпадение data-col строк с номерами столбцов линейки #colHeader.
  // Теперь offset — ЧИСТО ВИЗУАЛЬНЫЙ и применяется ОДИН РАЗ ко всей картинке разом (одинаковым
  // transform на строках и на линейке, см. render()/renderColHeader()) — данные, нумерация
  // столбцов и все расчёты его вообще не видят, а картинка едет целиком, как и просили
  // ("сдвигает всё, кроме паттернов; что наезжает на паттерны — прячется за ними").
  if (align === "left") return 0;
  if (align === "right") return diff;
  // ЛЕСЕНКИ считают ступеньку от НОМЕРА СТРОКИ (rowIdx), а НЕ от её длины — запрос пользователя:
  // "две строки «1» и «1» стоят 1 под 1, а надо со смещением". При старой формуле (от длины)
  // сдвиг был функцией ТОЛЬКО длины, поэтому любые строки одинаковой длины неизбежно вставали
  // ровно друг под друга, сколько бы их ни было. От номера же лестница идёт ровно вниз всегда,
  // независимо от того, какие строки в таблице.
  // Инвариант "shift+len <= maxLen" тут НАМЕРЕННО не соблюдается (общая ширина у нижних строк
  // становится БОЛЬШЕ maxLen) — места, где остаток паддинга мог бы уйти в минус, подстрахованы
  // Math.max(0, …) по месту вызова.
  // "Лесенка" (↘, data-val="stairs") — шаг +1 колонка на строку.
  if (align === "stairs") return stairsUnits(align, ri);
  // "Лесенка ½" (↘½, data-val="halfstairs") — та же лестница, но вдвое положе: шаг +0.5 на
  // строку. Целая часть — здесь, недостающие 0.5 символа у НЕЧЁТНЫХ строк довешивает
  // transform:translateX в render() (см. extraCh/hasHalfNudge), тем же приёмом, что и "Центр ½".
  if (align === "halfstairs") return stairsUnits(align, ri) >> 1;
  // "Лесенка правая" (↙, data-val="rstairs") — зеркало обычной: строка НЕ реверсируется (читается
  // слева направо), но диагональ идёт по ПОСЛЕДНЕМУ биту строки. Правый край (shift+len−1) должен
  // идти 0,−1,−2,… по номеру строки, откуда shift = −ri − (len−1). Левый край при этом свободно
  // уезжает в минус (см. общий код отрицательного сдвига в render() — "if (shift < 0) extraCh
  // += shift;", он не завязан на конкретное выравнивание).
  if (align === "rstairs") return -stairsUnits(align, ri) - (len ? len - 1 : 0);
  // "Лесенка правая ½" (↙½, data-val="rhalfstairs") — то же, но правый край шагает на −0.5 за
  // строку: shift = −ri/2 − (len−1). Целая часть вниз (для отрицательных Math.floor уводит
  // «дальше в минус»), полсимвола у нечётных строк — тем же transform, что и у "Лесенка ½".
  if (align === "rhalfstairs") return -Math.ceil(stairsUnits(align, ri) / 2) - (len ? len - 1 : 0);
  return (diff >> 1);
}

function invertBits(s){ let o = ""; for (const c of s) o += (c === "0" ? "1" : c === "1" ? "0" : c); return o; }
function reverseStr(s){ return s.split("").reverse().join(""); }

/* Следующий виток кольца для кольцевого поиска (см. findPatternKinds) — по умолчанию точная
   копия строки (обычное кольцо), 🔁 Инв. кольцо (st.ringInvert) инвертирует биты (0↔1) витка,
   🔁 Инв. кольцо реверс (st.ringReverse) вдобавок реверсирует порядок бит витка — оба применяются
   независимо (можно включить один, другой, оба или ни одного), как и просил пользователь: 111
   даёт кольцо 111 000 111 000... с инверсией. */
function ringNextLap(text){
  let out = text;
  if (st.ringInvert) out = invertBits(out);
  if (st.ringReverse) out = reverseStr(out);
  return out;
}

/* ПОЛНЫЙ ПЕРИОД кольца. Обычное кольцо повторяет саму строку, период = её длина. Но с
   🔁 Инв. кольцо/реверс следующий виток ДРУГОЙ, а к себе строка возвращается только через ДВА
   витка (invert(invert)=исходная, reverse(reverse)=исходная, вместе тоже) — значит настоящий
   период вдвое длиннее, а привычное "прямое + инверсия" это лишь ПОЛОВИНА кольца (запрос
   пользователя: "прямое+инверсия = это полукольцо, надо его удвоить и в нём искать, чтобы по
   краям можно было найти паттерн"). Поиск (findPatternKinds) и показ результата (bgResultHtml
   в render()) обязаны брать ОДИН И ТОТ ЖЕ период, иначе подсветка находки разъедется с тем, что
   реально искали. Когда инверсия/реверс выключены, виток равен строке и всё сводится к прежнему
   поведению: период = длина, показ = строка + её копия. */
function ringCycle(text){
  // "🚫 Без кольца" (st.ringOff) — кольца нет вообще: период равен самой строке, второго витка
  // (в т.ч. инвертированного/реверснутого) не существует, поиск идёт только ВНУТРИ строки.
  if (st.ringOff) return text;
  const lap2 = ringNextLap(text);
  return lap2 === text ? text : text + lap2;
}

/* Проверка "текст содержит паттерн как подстроку" — целиком / без 1-го символа / реверсом /
   реверсом без 1-го, СТРОГО с учётом галок st.skipFirst и st.allKinds (как везде в
   приложении). Используется Гориз.XOR (генерация И скольжение) вместо общего findMatch(),
   у которого нет понятия "именно СВОЙ паттерн этой строки" — он сканирует ЛЮБЫЕ паттерны
   вперёд по списку, включая ещё не построенные строки, и потому даёт ложные срабатывания. */
/* ИСКОМЫЙ КУСОК ПАТТЕРНА с учётом обеих отсечек: "⏭ Без 1-го" (st.skipFirst) срезает первый символ,
   "⏮ Без посл." (st.skipLast) — последний. Включены обе — срезаются оба края. Короче двух символов
   не режем: резать там нечего, иначе паттерн исчез бы целиком. Одна функция на всё приложение,
   чтобы поиск, подсветка и подсказки резали одинаково. */
function patBase(t){
  let out = t || "";
  if (st.skipFirst && out.length > 1) out = out.slice(1);
  if (st.skipLast && out.length > 1) out = out.slice(0, -1);
  return out;
}
/* ⇌ ИНВ/РЕВ — ЧЕТЫРЕ ПОЛОЖЕНИЯ ВМЕСТО ГАЛКИ (v0.912, запрос пользователя "эту кнопку раздельно:
   вкл только реверс, инверсия и реверс, только инверсия, только прямой"). ПРЯМОЙ вариант паттерна
   ищется ВСЕГДА (подтверждено пользователем) — кнопка только ДОБАВЛЯЕТ к нему версии:
     ""       — только прямой (прежнее "галка снята");
     "rev"    — прямой + реверс;
     "invrev" — прямой + инверсия + реверс (+ инверсия-с-реверсом там, где такой kind есть) —
                это ровно прежнее "галка стоит";
     "inv"    — прямой + инверсия.
   st.allKinds остаётся булевым "включена хоть одна лишняя версия" — на него завязаны ключи мемо-
   кэшей и ветвления, где важен только сам факт; ГДЕ ИМЕННО перебираются версии, там теперь
   спрашивают kindsInvOn()/kindsRevOn() по отдельности. Держать оба в синхроне обязан
   setKindsMode(). */
const KINDS_MODES = ["", "rev", "invrev", "inv"];
const KINDS_MODE_LABELS = { "": "⇌ Прямой", rev: "⇌ +Реверс", invrev: "⇌ +Инв+Рев", inv: "⇌ +Инверсия" };
function kindsInvOn(){ const m = st.kindsMode || ""; return m === "inv" || m === "invrev"; }
function kindsRevOn(){ const m = st.kindsMode || ""; return m === "rev" || m === "invrev"; }
function textMatchesPattern(text, patText){
  if (!patText) return false;
  // Порядок как в findMatch(): сначала срез первого символа («Без 1-го»), инверсия/реверс —
  // от уже урезанной строки, а не наоборот (см. findPatternKinds() выше — тот же фикс).
  const base = patBase(patText);
  if (text.indexOf(base) >= 0) return true;
  // Версии перебираются ПО ОТДЕЛЬНОСТИ — см. KINDS_MODES/kindsInvOn/kindsRevOn.
  if (kindsInvOn() && text.indexOf(invertBits(base)) >= 0) return true;
  if (kindsRevOn() && text.indexOf(reverseStr(base)) >= 0) return true;
  return false;
}

/* Та же проверка, что textMatchesPattern(), но вместо true/false (первого найденного варианта)
   возвращает МАССИВ {kind,start,end,len,skip} — ПО ОДНОЙ записи на КАЖДУЮ версию паттерна (прямая
   kind=0, инверсия kind=1, реверс kind=2, инверсия+реверс СРАЗУ kind=3 — четвёртый вариант, не
   пересекающийся с обычной таблицей паттернов, только для этого окошка результата), которая
   реально нашлась в тексте. Для каждой версии проверяются ОБА варианта — "как есть" и без 1-го
   символа (⏭ Без 1-го) — берётся более ранняя позиция, а найденный skip:true/false запоминается
   отдельно, чтобы в подсветке можно было показать, что сработал именно "без 1-го" вариант.
   kind 0..2 — те же коды, что и везде в приложении (см. KIND_CLS). Используется для подсветки в
   окошке результата фон-поиска (см. render() → bgResultHtml), чтобы показать НЕ только
   "нашлось", но и КАКИЕ ИМЕННО версии (может найтись сразу несколько одновременно).
   Поиск КОЛЬЦЕВОЙ (как и основной findMatch() выше по файлу) — результирующая строка (Интерлив/
   XOR/Сквозная и т.д.) считается ЗАМКНУТОЙ САМОЙ НА СЕБЯ, поэтому паттерн, "переезжающий" через
   конец строки обратно в её начало, тоже засчитывается как найденный. Технически: ищем не в
   самом text, а в text+продолжение (без последнего символа, чтобы не находить тривиальный
   повтор всей строки) — совпадение принимается, только если оно НАЧИНАЕТСЯ внутри исходного
   text (idx<len), а start/end хранятся уже по модулю len (end < start означает, что находка
   "перешла" через конец строки — см. отрисовку в render(), где диапазон [start..end] обходится
   циклически). Продолжение по умолчанию — точная копия text (обычное кольцо); если включена
   🔁 Инв. кольцо (st.ringInvert) — продолжение ИНВЕРТИРОВАНО (0↔1): 111 даёт кольцо
   111 000 111 000..., а не 111 111 111... — это свойство самих ДАННЫХ строки, поэтому кольцо
   строится один раз из text/invertBits(text), одинаково для всех kind (0..3). */
function findPatternKinds(text, patText){
  const len = text.length;
  if (!patText || !len) return [];
  // Ищем в ПЕРИОДЕ кольца, удвоенном без последнего символа (чтобы не находить тривиальный
  // повтор всего периода целиком). При выключенных инверсии/реверсе период = сам text, и
  // выражение сводится к прежнему text + text.slice(0, len-1).
  const cycle = ringCycle(text);
  const period = cycle.length;
  // "🚫 Без кольца" — никакого замыкания: ищем ровно в самой строке, находка через её край не
  // засчитывается (запрос пользователя).
  const ring = st.ringOff ? cycle : (period > 1 ? cycle + cycle.slice(0, period - 1) : cycle);
  // Порядок как в основном движке findMatch() (см. p.s0/s1/s2 там): СНАЧАЛА срезаем первый
  // символ паттерна («Без 1-го»), и только ПОТОМ считаем инверсию/реверс от уже урезанной
  // строки — не наоборот. Раньше было наоборот (инверсия/реверс полного паттерна, а срез —
  // уже после), из-за чего для kind 1..3 подсвечивался кусок, не совпадающий с тем, что
  // реально ищет обычный поиск (findMatch), и вводило в заблуждение.
  const skipApplied = st.skipFirst && patText.length > 1;
  const base = patBase(patText);
  const out = [];
  // "Подпаттерны сдвига" (st.bgSubPatterns): вместо ОДНОГО варианта на kind проверяем ВСЕ его
  // циклические сдвиги — найдено, если совпал хоть один. tried[] хранит ПОЛНЫЙ разбор (все
  // варианты и кто из них совпал) для каждого kind, даже если в итоге ничего не нашлось — это
  // нужно "Черновику последнего шага" (см. renderStepLogBox), чтобы показать список целиком.
  const tried = [];
  const tryKind = (kind, full) => {
    const candidates = st.bgSubPatterns ? rotationsOf(full) : [full];
    const variants = candidates.map(cand => {
      const idx = ring.indexOf(cand);
      // Начало находки может лежать В ЛЮБОМ месте периода (в т.ч. во втором, инвертированном
      // витке) — раньше тут стояло idx < len, т.е. половина кольца в поиске не участвовала.
      const found = idx >= 0 && idx < period;
      return { text: cand, found, start: found ? idx : -1 };
    });
    const hit = variants.find(v => v.found);
    tried.push({ kind, base: full, variants, matched: !!hit });
    if (hit) out.push({ kind, start: hit.start, end: (hit.start + hit.text.length - 1) % period, len: hit.text.length, skip: skipApplied, sub: hit.text !== full ? hit.text : null });
  };
  tryKind(0, base);
  // Каждая версия — по своему тумблеру (см. KINDS_MODES). kind 3 (инверсия+реверс сразу) требует
  // обеих: это не отдельная версия, а их наложение.
  const inv = invertBits(base);
  if (kindsInvOn()) tryKind(1, inv);
  if (kindsRevOn()) tryKind(2, reverseStr(base));
  if (kindsInvOn() && kindsRevOn()) tryKind(3, reverseStr(inv));
  out.tried = tried;
  // Период кольца едет вместе с результатом — buildHitMap() раскладывает kd.start по позициям и
  // обязан знать, по какому модулю сворачивать (при 🔁 Инв. кольцо период вдвое длиннее строки,
  // и по модулю её длины находка из второго витка легла бы не на те биты). Так период получают
  // ВСЕ потребители без правки сигнатур; массивы kinds, собранные вручную (напр. [hit] в
  // computeHorizXorInfo), поля не имеют — там buildHitMap честно откатится на len.
  out.period = period;
  return keepBestKind(out);
}
/* ТОЛЬКО ОДНА ВЕРСИЯ НАХОДКИ НА РЕЗУЛЬТАТ (v0.917, запрос пользователя: "если нашлась прямая
   находка — жёлтым, и другие инверс/реверс не показывать вообще, затем реверс, и потом только
   инверс, если ничего не нашлось").
   Раньше отдавались ВСЕ совпавшие версии сразу: в строке результата стояло по галочке ✓ на
   каждую, а подсветка красила куски разными цветами вперемешку — по прямой находке было не
   понять, она это или случайно легшая рядом инверсия. Теперь из списка остаётся ровно одна
   версия — старшая из найденных, а её вхождений может быть несколько (подпаттерны/повторы).
   Старшинство: прямой → реверс → инверсия → инверсия+реверс. Реверс выше инверсии — так просил
   пользователь: развёрнутый паттерн это та же фигура, а инвертированный уже другая.
   Фильтруем ЗДЕСЬ, в одной точке, а не в отрисовке: тем же списком живут галочки ✓, matched,
   лог и захват находки — расходиться им нельзя. Диагностика (out.tried) не трогается: в
   "Черновике" по-прежнему видно, какие версии пробовались и что из них совпало. */
const KIND_PRIORITY = [0, 2, 1, 3];
function keepBestKind(kinds){
  if (!kinds || kinds.length < 2) return kinds;
  for (const k of KIND_PRIORITY) {
    const only = kinds.filter(x => x.kind === k);
    if (!only.length) continue;
    only.tried = kinds.tried;
    only.period = kinds.period;
    return only;
  }
  return kinds;
}

/* "По подсветке" (см. #bSearchOnlyHl в "Виде"): строит СВОЮ строку из "0"/"1" для
   строки r — "1" там, где позиция ПРЯМО СЕЙЧАС подсвечена цветом (объединение ВКЛЮЧЁННЫХ
   подсветок "1↕1"/"1⤡1"), остальные позиции — "0", НЕЗАВИСИМО от исходного бита в st.rows.
   У подсветки "01" логика ОБРАТНАЯ: "1" там, где позиция НЕ входит в её пробег ("01" красит и
   часть нулей тоже — раз она включена, именно эти закрашенные позиции считаются "0", а всё
   остальное — "1"). Если ни одна подсветка не включена — строка выйдет вся из нулей. Использует
   те же compute01HighlightMask/computeVertOnesMask/computeDiagOnesMask, что и сам render().
   "⧅⧄ Диагонали склейки" (computeDiagFoldMask) в этот фильтр НАМЕРЕННО не входит: она красит не
   находки, а сами линии обхода (и нули тоже), и её единственный смысл — показать, что именно
   складывают режимы "Диаг."; загонять её ещё и во ВХОД поиска — это ссылка на саму себя. */
function computeHighlightedOnlyRow(st, r) {
  const s = st.rows[r] || "";
  if (!s.length) return s;
  let mask = null;
  if (st.highlight01) {
    const m = compute01HighlightMask(s);
    mask = new Set();
    for (let k = 0; k < m.length; k++) if (!m[k]) mask.add(k);
  }
  if (st.highlightVert1) {
    const vm = computeVertOnesMask(st.rows, st.align)[r];
    if (vm) { if (!mask) mask = new Set(); vm.forEach(k => mask.add(k)); }
  }
  if (st.highlightDiag1) {
    const dm = computeDiagOnesMask(st.rows, st.align)[r];
    if (dm) { if (!mask) mask = new Set(); dm.forEach(k => mask.add(k)); }
  }
  let out = "";
  for (let k = 0; k < s.length; k++) out += (mask && mask.has(k)) ? "1" : "0";
  return out;
}

/* Получение символов строки с учетом возможного инверсного повторного захода */
/* ВЕРХНЯЯ ГРАНИЦА УЧАСТИЯ ПОСТРОЕНИЙ (запрос пользователя): построено сверху, скажем, 40 строк,
   а выделена строка 10 — работают только зеркала строк 1..10, то есть построения -10..-1. Всё, что
   выше (-11 и дальше), в расчётах не участвует вовсе и в таблице затемнено. Возвращает индекс первой
   строки, которая идёт в дело; без построений — 0, то есть всё как всегда.
   Считается по ВЫДЕЛЕННОЙ строке: её номер и говорит, до какого зеркала верх осмыслен. Выделена
   нулевая или сама построенная строка — верх не участвует целиком. */
/* Граница показа зеркал: они рисуются только до самой нижней выделенной строки (см. render).
   ГОРЯЧАЯ ФУНКЦИЯ: зовётся из mirroredRowBits()/mirrorPadsOf(), то есть на КАЖДОЕ чтение строки
   в каждом режиме фон-поиска — десятки тысяч раз за кадр. Поэтому обычный цикл, а не
   Math.max(...set): спред на каждом вызове ещё и создаёт массив аргументов длиной с выделение
   (а оно бывает в сотни строк) — на этом интерфейс и начинал заметно тормозить. */
function mirrorBoundRow(){
  const sel = st.selectedRows;
  if (!sel || !sel.size) return -1;
  let mx = -1;
  for (const r of sel) if (r > mx) mx = r;
  return mx;
}
/* ВЕРХНЯЯ граница показа зеркал. Выделена РОВНО ОДНА строка — зеркало строится ТОЛЬКО для неё
   (запрос пользователя: "зеркало потом строить только для одной строки при каждом шаге и его биты
   наверх"): при работе "⇔ Зеркалом шагами" таблица разбирается по строке за шаг, и зеркала у всех
   строк выше — лишняя картинка, которая вдобавок идёт в поиск наравне с настоящими битами.
   Выделено несколько строк (или ни одной) — всё как было: от самого верха и до нижней выделенной. */
function mirrorTopRow(){
  return (st.selectedRows && st.selectedRows.size === 1) ? mirrorBoundRow() : 0;
}
/* Показывается ли зеркало у строки r — одна проверка на всех (показ, поиск по зеркалам, счёт
   столбцов, вписывание). Тоже горячая (см. mirrorBoundRow): выделение обходим ОДИН раз и без
   спреда, а у одной выделенной строки вообще выходим сразу — сравнение с ней и есть весь ответ. */
function mirrorRowShown(r){
  const sel = st.selectedRows;
  if (!sel || !sel.size) return false;
  if (sel.size === 1) { for (const only of sel) return r === only; }
  let mx = -1;
  for (const x of sel) if (x > mx) mx = x;
  return r <= mx;
}
/* ВИД ЗЕРКАЛ (кнопка "⇔ Зеркала", st.mirrorKind). Сначала вариант был один — отражение с
   инверсией; по запросу пользователя добавлены половинки по отдельности и вовсе без них:
     "revinv" — реверс + инверсия (как было раньше, значение по умолчанию);
     "rev"    — только реверс: строка отражается, биты остаются как есть;
     "inv"    — только инверсия: порядок бит как в строке, значения 0↔1;
     "none"   — копия строки как есть.
   Сюда приходит уже отрезанный кусок строки (опорный бит отрезает вызывающий — он в зеркало не
   входит), поэтому длина зеркала от вида не зависит и mirrorPadsOf() менять не пришлось. Через
   эту функцию идут ВСЕ три места, где зеркало строится: серый показ в render(), поиск по
   зеркалам (mirroredRowBits ниже) и вписывание в данные (applyMirrorsToRows). Вид общий для
   левого и правого РАЗНЫЙ (запрос пользователя: "для лев, прав — отдельно"): st.mirrorKindL и
   st.mirrorKindR, сторона приходит вторым доводом — "l" или "r". */
const MIRROR_KINDS = ["revinv", "rev", "inv", "none"];
function mirrorKindOf(side){
  const k = side === "r" ? st.mirrorKindR : st.mirrorKindL;
  return MIRROR_KINDS.indexOf(k) >= 0 ? k : "revinv";
}
function mirrorSideBits(s, side){
  const k = mirrorKindOf(side);
  if (k === "rev")  return reverseStr(s);
  if (k === "inv")  return invertBits(s);
  if (k === "none") return s;
  return invertBits(reverseStr(s));
}
/* Строка ВМЕСТЕ С ПОКАЗАННЫМИ ЗЕРКАЛАМИ — то, что реально видно на экране. Пока зеркала не вписаны
   в данные, они всё равно остаются битами картинки, и по запросу пользователя поиск обязан считать
   ИМЕННО ИХ: "поиск в любом случае, если показаны зеркала — по всем битам, а не только по реальным".
   Зеркала выключены (или строка ниже границы показа) — отдаётся сама строка, без изменений. */
/* "⊘ Ось ◀/▶" (st.mirrorCutAxisL/R) — убирать ли САМ опорный бит зеркала этой стороны. Опорный
   бит — первый бит строки для левого зеркала и последний для правого: в само зеркало он не входит
   никогда, но до сих пор ОСТАВАЛСЯ в строке единственным центром симметрии ("1011" + левое
   зеркало = [зеркало от "011"] + "1011"). С включённой кнопкой он исчезает совсем — [зеркало от
   "011"] + "011", — и половинки смыкаются без центра (запрос пользователя "ещё для каждой удалять
   осевой бит"). Флаг стороны считается только когда зеркало этой стороны ВКЛЮЧЕНО: выключенному
   зеркалу нечего резать. */
function mirrorCutOf(side){
  return side === "r" ? (!!st.rightMirror && !!st.mirrorCutAxisR)
                      : (!!st.leftMirror && !!st.mirrorCutAxisL);
}
/* Часть строки, которая остаётся МЕЖДУ зеркалами, с учётом срезанных опорных битов. Обе стороны
   могут резать одновременно (строка из двух бит при этом исчезает целиком, остаются только два
   зеркала — это законно, отдельной ветки не нужно). */
function mirrorCoreBits(s){
  const a = mirrorCutOf("l") ? 1 : 0;
  const b = s.length - (mirrorCutOf("r") ? 1 : 0);
  return b > a ? s.slice(a, b) : "";
}
function mirroredRowBits(r){
  const s0 = st.rows[r] || "";
  if (s0.length < 2) return s0;
  if (!st.leftMirror && !st.rightMirror) return s0;
  if (!mirrorRowShown(r)) return s0;
  const l = st.leftMirror ? mirrorSideBits(s0.slice(1), "l") : "";
  const rr = st.rightMirror ? mirrorSideBits(s0.slice(0, -1), "r") : "";
  return l + mirrorCoreBits(s0) + rr;
}
/* Сколько бит приписали к строке ПОКАЗАННЫЕ зеркала слева и справа — ровно по тем же условиям,
   что и mirroredRowBits() выше. Нужно всем, кто считает КОЛОНКИ (XOR, интерлив): на экране
   зеркало ВИСИТ СБОКУ от строки и на её выравнивание не влияет — render() берёт сдвиг по
   СОБСТВЕННОЙ длине строки (см. geomLen там), а зеркало печатает внутри её левого отступа.
   Значит и в расчёте столбцов сдвиг надо считать от собственной длины, а начало строки С
   ЗЕРКАЛОМ — сдвинуть влево ровно на его длину. Раньше зеркала входили в строку как обычные
   биты, и "По центру" центровало строку ВМЕСТЕ с ними — колонки XOR разъезжались с картинкой
   (запрос пользователя: "XOR-Все при выравнивании центр неверно при включенном зеркале влево"). */
function mirrorPadsOf(st, r){
  const none = { l: 0, r: 0 };
  // "Искать только по подсвеченному" отдаёт СВОЮ строку (computeHighlightedOnlyRow) — зеркал в
  // ней нет вовсе, см. getRowBits().
  if (!st || st.searchOnlyHighlighted) return none;
  if (!st.leftMirror && !st.rightMirror) return none;
  const s0 = st.rows[r] || "";
  if (s0.length < 2) return none;
  if (!mirrorRowShown(r)) return none;
  // Срез опорного бита ("⊘ Ось", mirrorCutOf) сюда НЕ входит и входить не должен: он убирает бит
  // из самой строки, а не приписывает/убирает биты зеркал — левое зеркало по-прежнему кончается
  // ровно там, где начинается строка, и точка отсчёта столбцов не двигается.
  return { l: st.leftMirror ? s0.length - 1 : 0, r: st.rightMirror ? s0.length - 1 : 0 };
}
/* КАРТИНКА НЕ ДОЛЖНА ПРЫГАТЬ, когда операция удлинила строку (запрос пользователя: "интерлив
   когда изменяет строку и результат длинный — не надо перемещать ось").
   Почему прыгала: точка отсчёта выравнивания — самая длинная строка таблицы. Стала строка вдвое
   длиннее — вырос maxLen, а вместе с ним и сдвиг КАЖДОЙ строки (у "По центру" на половину
   прибавки, у "По правому краю" на всю, у осевых — вместе с осью), и вся цепочка уезжала вбок,
   иногда за край экрана.
   Лечится общим ВИЗУАЛЬНЫМ сдвигом полотна (st.axisCenterOffset — та же ручка #axisSplit): меряем,
   где стояла строка-ориентир ДО операции, и после операции возвращаем полотно ровно на столько же.
   В данные это не входит вообще (см. alignShift) — столбцы, склейки и поиск его не видят. */
function axisAnchorShift(anchorIdx){
  const s = st.rows[anchorIdx] || "";
  if (!s.length) return null;
  let maxLen = 0;
  for (const r of st.rows) if (r && r.length > maxLen) maxLen = r.length;
  // В ПОЛУСТОЛБЦАХ (×2): у "½"-выравниваний половина позиции живёт не в целочисленном сдвиге, а в
  // полушаге (render кладёт его отдельным transform, см. extraCh += 0.5 там же). Мерить одним лишь
  // rowShiftFor мало: смена чётности maxLen перекидывает строку в другую подсетку, и картинка
  // уезжала на полстолбца даже с компенсацией (запрос пользователя — "↔½ съезжает также").
  const isHalfAlign = st.align === "halfcenter" || st.align === "halfstairs" || st.align === "rhalfstairs";
  return 2 * rowShiftFor(maxLen, anchorIdx, s, st.align) +
    (isHalfAlign && hasHalfNudge(s, maxLen, st.align, anchorIdx) ? 1 : 0);
}
/* ОТКЛЮЧЕНО (запрос пользователя: "когда строка меняет длину не надо двигать ось — пусть ось
   перемещается только вручную"). Раньше тут гасилось смещение полотна, которое возникает, когда
   операция изменила длину строки и выравнивание пересчиталось от нового maxLen: полотно ехало
   само, и это выглядело как прыжок картинки. Теперь ось стоит там, где её поставили ручкой
   #axisSplit, и НИЧТО, кроме самой ручки, её не двигает — картинка едет, ось нет.
   Функция и её замеры (axisAnchorShift) оставлены на месте: вызовы разбросаны по операциям, и
   пустое тело выключает механизм разом, ничего не ломая. */
function keepAxisAfter(anchorIdx, before){
  return;
  /* eslint-disable no-unreachable */
  if (before == null) return;
  const after = axisAnchorShift(anchorIdx);
  if (after == null || after === before) return;
  // Считали в полустолбцах — гасим половиной разницы (дробные полстолбца полотну не помеха:
  // extraCh в render() и так считает в долях колонки).
  st.axisCenterOffset = (st.axisCenterOffset || 0) - (after - before) / 2;
}
function firstActiveRow(){
  const built = st.topBuilt || 0;
  if (!built) return 0;
  if (!st.selectedRows || !st.selectedRows.size) return 0;
  let sel = -1;
  for (const r of st.selectedRows) if (r > sel) sel = r;
  const label = sel - built;
  if (label <= 0) return built;
  return Math.max(0, built - label);
}
/* "⋮ Биты: чёт/нечёт" (st.parityView, кнопка #bParityView в "Правке строк") — ПОКАЗ через один
   бит. Значения:
     0 — выкл (всё как обычно);
     1 — чётные биты СВОЕЙ строки (позиции 2,4,6… считая от 1);
     2 — нечётные биты своей строки (1,3,5…);
     3 — чётные ПО СКВОЗНОЙ: нумерация не начинается заново в каждой строке, а идёт непрерывно
         с самого первого бита ПЕРВОЙ строки, так что чётность строки зависит от суммы длин всех
         строк выше;
     4 — нечётные по сквозной.
   Выключённые биты не стираются из данных — они заменяются ТОЧКОЙ ".": на экране на их месте
   стоит точка, а во всех результатах (склейки, XOR, интерлив, поиск, сквозная) их нет ВООБЩЕ —
   не ноль, а именно "бита тут нет", как у чужой полусетки на "½"-выравниваниях (см. stripDots и
   проверки !== "." в vertColHasBit/xorRowsFiltered/diagPathBits/interleavePairRows).
   Данные строк не меняются — поэтому нажатия перебираются свободно и всегда считаются от
   ИСХОДНОЙ строки, а не от уже проредённой. */
function parityChainOffset(rowIdx){
  let n = 0;
  for (let i = 0; i < rowIdx; i++) n += (st.rows[i] || "").length;
  return n;
}
/* padL/padR — показанные зеркала (см. mirrorPadsOf): они НЕ прореживаются (на экране зеркала
   рисуются целиком), маска накладывается только на собственные биты строки, и позиция считается
   от её первого настоящего бита. */
function applyParityMask(s, rowIdx, padL, padR){
  const m = st.parityView || 0;
  if (!m || !s) return s;
  const l = padL || 0, r = s.length - (padR || 0);
  const off = (m >= 3) ? parityChainOffset(rowIdx) : 0;
  const want = (m === 1 || m === 3) ? 1 : 0; // чёт: (позиция от 1) чётная ⇔ индекс нечётный
  let out = "";
  for (let k = 0; k < s.length; k++){
    const ch = s[k];
    if (k < l || k >= r || (ch !== "0" && ch !== "1")) { out += ch; continue; }
    out += (((off + k - l) % 2) === want) ? ch : ".";
  }
  return out;
}
/* Убрать точки из готовой строки — для тех расчётов, что читают строку подряд, а не по столбцам
   (сквозная, горизонтальные склейки, интерлив/XOR пары по индексам). */
function stripDots(s){ return (s && s.indexOf(".") >= 0) ? s.replace(/\./g, "") : s; }
function getRowBits(st, r) {
  // Построения выше границы участия для любых расчётов — пустая строка: так они выпадают из ВСЕХ
  // склеек, XOR-ов и фон-поиска разом, без отдельной ветки в каждом режиме. Проверка стоит под
  // условием st.topBuilt, поэтому без построений не стоит ничего.
  if (st.topBuilt && r < firstActiveRow()) return "";
  // Показанные зеркала идут в расчёты наравне с настоящими битами (см. mirroredRowBits).
  const raw = st.searchOnlyHighlighted ? computeHighlightedOnlyRow(st, r) : mirroredRowBits(r);
  // Прореживание "⋮ Биты: чёт/нечёт" — ПОСЛЕДНИМ слоем, поверх зеркал и инверсии прохода:
  // выключенные биты становятся точками и дальше выпадают из всех расчётов (см. applyParityMask).
  const bits = (st.invPass && (st.passCount % 2 === 1)) ? invertBits(raw) : raw;
  if (!st.parityView) return bits;
  const pads = mirrorPadsOf(st, r);
  return applyParityMask(bits, r, pads.l, pads.r);
}

/* Интерливинг пары. Необязательный 5-й параметр N (по умолчанию 1) — БЛОЧНЫЙ интерлив: вместо
   чередования по одному символу берутся блоки по N символов подряд с каждой стороны (см.
   "Интерлив сквозной" / st.interleaveSeqBlockN — запрос пользователя: "если не наход, то делает
   интерливинг не через 1 бит а через 2 бита потом через 3 и тд"). N=1 даёт РОВНО ТОТ ЖЕ результат,
   что и раньше (побитовый интерлив) — остальные вызовы (обычный "⧬ Интерлив", фон-поиск и т.д.)
   N не передают и не меняются. */
/* Простое чередование по индексу — читаем обе строки слева направо ОДНОВРЕМЕННО ("шахматкой"):
   верх[0], низ[0], верх[1], низ[1], ... без всякого сдвига по выравниванию (запрос
   пользователя: "111"+"1000" → "111010" — верх и низ читаются с одной и той же стартовой
   позиции 0, никакого смещения). Хвост более длинной строки, у которого нет пары сверху/
   снизу, ОТБРАСЫВАЕТСЯ целиком, а не дописывается в одиночку — align тут больше не участвует
   (align по-прежнему используется отдельно, напр. при паддинге перед XOR). */
function interleavePair(top, bot, align, N){
  N = N || 1;
  top = stripDots(top); bot = stripDots(bot); // точки "⋮ чёт/нечёт" в переплетение не идут
  const len = Math.min(top.length, bot.length);
  let out = "";
  for (let i = 0; i < len; i += N){
    out += top.slice(i, i + N) + bot.slice(i, i + N);
  }
  return out;
}

/* Карта "какой kind (и его skip-флаг) покрывает эту позицию" для подсветки найденного паттерна
   поверх готового HTML-результата (см. interleavePairMarked/xorPairMarked ниже) — тот же приём,
   что и у bgResultHtml в render() (kindAt/skipAt), только по модулю периода кольца вместо физического
   продолжения строки: находка, "заехавшая" за конец (kd.end < kd.start), просто подсвечивается
   ДВУМЯ кусками — в хвосте и в начале ТОГО ЖЕ отображаемого результата, без лишнего "довеска"
   кольца в самом Итоге (кольцо и так уже показано отдельно, в "Скв×2"). Первый (самый ранний)
   kind по позиции — приоритетный, как и в bgResultHtml. */
function buildHitMap(len, kinds){
  const map = new Array(len).fill(null);
  if (!kinds || !len) return map;
  // Сворачиваем по ПЕРИОДУ кольца (kinds.period, см. findPatternKinds), а не по длине показанной
  // строки. Без инверсии/реверса период равен len и всё как раньше. С 🔁 Инв. кольцо период
  // вдвое длиннее: позиции второго витка — это ИНВЕРТИРОВАННЫЕ биты, в "Итоге" (там показан один
  // прямой виток) их попросту нет, поэтому такие позиции пропускаем, а не красим ими чужие биты.
  // Часть находки, ушедшая за период и завернувшаяся обратно в прямой виток, при этом
  // подсвечивается правильно — она сворачивается в q < len.
  const P = (kinds && kinds.period) || len;
  for (const kd of kinds) {
    for (let i = 0; i < kd.len; i++) {
      const q = (kd.start + i) % P;
      if (q < len && !map[q]) map[q] = { kind: kd.kind, skip: kd.skip };
    }
  }
  return map;
}

/* То же самое переплетение, что и interleavePair(seqStr, rowStr, align), но вместо строки
   возвращает ГОТОВЫЙ HTML: ВСЕ символы (и "0", и "1"), взятые ИЗ СТРОКИ (не из сквозной),
   красятся синим (.interleave-src-row в CSS) — независимо от значения бита; символы сквозной —
   обычным цветом по значению бита (.b0/.b1). Используется "⧬ Интерлив сквозной", чтобы было
   видно, куда легли именно биты строки среди переплетения (см. запрос пользователя — фон
   пробовали, оказалось неразборчиво; сначала красили только "1" из строки, потом добавили и "0").
   Необязательный 4-й параметр kinds (результат findPatternKinds(searchResult, patFull)) —
   ДОПОЛНИТЕЛЬНО подсвечивает сам НАЙДЕННЫЙ паттерн (.chain-hit-bits, см. buildHitMap выше) —
   иначе по "Итогу" не видно, ГДЕ именно совпадение, только что оно есть (см. запрос
   пользователя — "не вижу в результирующей нахождения паттерна"). Позиция в HTML считается
   ЖИВЫМ счётчиком pos (не индексом i) — порядок символов в выводе interleavePair() не 1:1 с i
   (за каждый i может уйти от 1 до 2×N символов), а kinds.start/end посчитаны по позиции в готовой
   ПЛОСКОЙ строке searchResult, поэтому индексировать map нужно именно этим счётчиком.
   Необязательный 6-й параметр N (по умолчанию 1) — та же блочность, что у interleavePair(N) выше,
   markBlock красит ЦЕЛИКОМ блок посимвольно (каждый символ блока — свой span, как и раньше). */
function interleavePairMarked(seqStr, rowStr, align, kinds, N){
  N = N || 1;
  seqStr = stripDots(seqStr); rowStr = stripDots(rowStr);
  // Та же простая логика, что и в interleavePair() выше — без сдвига по выравниванию,
  // хвост более длинной строки без пары отбрасывается (не рисуется).
  const len = Math.min(seqStr.length, rowStr.length);
  let outLen = 0;
  for (let i = 0; i < len; i += N) outLen += Math.min(N, seqStr.length - i) + Math.min(N, rowStr.length - i);
  const hitAt = buildHitMap(outLen, kinds);
  let pos = 0;
  const markBlock = (str, isRow) => {
    let out = "";
    for (const ch of str) {
      const cls = [isRow ? 'interleave-src-row' : ('b' + ch)];
      const hit = hitAt[pos++];
      if (hit) { cls.push('chain-hit-bits'); if (KIND_CLS[hit.kind]) cls.push(KIND_CLS[hit.kind]); if (hit.skip) cls.push('skip1'); }
      out += '<span class="' + cls.join(" ") + '">' + esc(ch) + '</span>';
    }
    return out;
  };
  let html = "";
  for (let i = 0; i < len; i += N){
    html += markBlock(seqStr.slice(i, i + N), false) + markBlock(rowStr.slice(i, i + N), true);
  }
  return html;
}

/* ХОР пары */
function xorPair(top, bot, align){
  top = stripDots(top); bot = stripDots(bot); // точки "⋮ чёт/нечёт" — не биты, в XOR не идут
  const useTop = top.length >= bot.length;
  const long = useTop ? top : bot, short = useTop ? bot : top;
  const shift = alignShift(long.length, short.length, align);
  let out = "";
  for (let i = 0; i < long.length; i++){
    const j = i - shift;
    if (j >= 0 && j < short.length && (long[i] === "0" || long[i] === "1") && (short[j] === "0" || short[j] === "1")){
      out += (long[i] === short[j]) ? "0" : "1";
    } else {
      out += long[i];
    }
  }
  return out;
}

/* То же самое, что xorPair(seqStr, rowStr, align), но вместо строки возвращает ГОТОВЫЙ HTML:
   позиции, где в XOR реально участвовал бит СТРОКИ (не только сквозной), красятся синим
   (.interleave-src-row в CSS, тот же класс, что и у "⧬ Интерлив сквозной" — общий смысл "тут
   есть вклад строки"), остальное — обычным цветом по значению бита. Используется "⨁ XOR
   сквозной" (см. запрос пользователя — "также надо чтобы работал Xor", по образцу интерливинга
   по сквозной). Необязательный 4-й параметр kinds — см. interleavePairMarked() выше, тот же
   приём подсветки найденного паттерна (.chain-hit-bits). xorPair() (в отличие от interleavePair)
   выдаёт РОВНО ОДИН символ на каждую i — здесь позиция в HTML совпадает с i один в один, поэтому
   отдельный счётчик pos не нужен. */
function xorPairMarked(seqStr, rowStr, align, kinds){
  seqStr = stripDots(seqStr); rowStr = stripDots(rowStr);
  const seqIsLong = seqStr.length >= rowStr.length;
  const long = seqIsLong ? seqStr : rowStr, short = seqIsLong ? rowStr : seqStr;
  const shift = alignShift(long.length, short.length, align);
  const hitAt = buildHitMap(long.length, kinds);
  let html = "";
  for (let i = 0; i < long.length; i++){
    const j = i - shift;
    const overlap = j >= 0 && j < short.length && (long[i] === "0" || long[i] === "1") && (short[j] === "0" || short[j] === "1");
    const ch = overlap ? ((long[i] === short[j]) ? "0" : "1") : long[i];
    const cls = [overlap ? 'interleave-src-row' : ('b' + ch)];
    const hit = hitAt[i];
    if (hit) { cls.push('chain-hit-bits'); if (KIND_CLS[hit.kind]) cls.push(KIND_CLS[hit.kind]); if (hit.skip) cls.push('skip1'); }
    html += '<span class="' + cls.join(" ") + '">' + esc(ch) + '</span>';
  }
  return html;
}

/* Сквозная склейка строк 0..stopIdx (включительно) без выравнивания/XOR — просто конкатенация.
   dir "right": обычный порядок сверху вниз (каждая следующая строка приклеивается справа).
   dir "left": обратный порядок — от stopIdx вверх до 0 (каждая следующая по счёту строка,
   идя сверху вниз, приклеивается слева, поэтому итог начинается с выделенной строки). */
/* Границы КАРТИНКИ по сетке текущего выравнивания для строк 0..stopIdx: самый левый и самый
   правый занятый столбец. Нужны сквозным склейкам при включённой "0 вместо пустот" — по ним
   каждая строка растягивается на общую ширину. Возвращает null, если непустых строк нет. */
function concatGridBounds(st, stopIdx){
  let maxLen = 0;
  for (const s of st.rows) if (s && s.length > maxLen) maxLen = s.length;
  let lo = Infinity, hi = -Infinity;
  for (let i = 0; i <= stopIdx; i++) {
    const s = getRowBits(st, i);
    if (!s.length) continue;
    const sh = rowShiftFor(maxLen, i, s, st.align);
    if (sh < lo) lo = sh;
    if (sh + s.length - 1 > hi) hi = sh + s.length - 1;
  }
  return (lo === Infinity) ? null : { lo: lo, hi: hi, maxLen: maxLen };
}
/* Одна строка, разложенная по этой сетке: свои биты на своих столбцах, пустые места слева и
   справа от строки — нулями. */
function concatRowPadded(st, i, g){
  const s = getRowBits(st, i);
  if (!s.length) return "";
  const sh = rowShiftFor(g.maxLen, i, s, st.align);
  let out = "";
  for (let c = g.lo; c <= g.hi; c++) {
    const j = c - sh;
    const chp = (j >= 0 && j < s.length) ? s[j] : "0";
    if (chp !== ".") out += chp;
  }
  return out;
}
function concatRowsDownTo(st, stopIdx, dir){
  let out = "";
  // С "0 вместо пустот" склейка идёт ПО СЕТКЕ выравнивания, а не по голым строкам: у голых строк
  // пустот нет вовсе, поэтому галка на сквозных не работала совсем, и результат не менялся от
  // сдвигов — сдвиг живёт в геометрии, а её тут не было (запрос пользователя). Без галки — прежнее
  // поведение слово в слово.
  const g = st.padZero ? concatGridBounds(st, stopIdx) : null;
  if (dir === "left") {
    for (let i = stopIdx; i >= 0; i--) out += g ? concatRowPadded(st, i, g) : stripDots(getRowBits(st, i));
  } else {
    for (let i = 0; i <= stopIdx; i++) out += g ? concatRowPadded(st, i, g) : stripDots(getRowBits(st, i));
  }
  return out;
}

/* "Сквозная Змейка" для фон-поиска (см. bgSearchModeGrp "concatSnake") — ПОСТРОЧНАЯ склейка
   0..stopIdx (включительно), как concatRowsDownTo(dir="right"), но у КАЖДОЙ ВТОРОЙ строки биты
   реверснуты — та же логика, что у seqGlueMode "snake" в horizChainText() (см. запрос
   пользователя). НЕ путать с concatSnakeDownTo() выше — там змейка ПО СТОЛБЦАМ (другая
   механика, отдельный режим "🐍 Змейка →/←"). */
function concatSnakeGlueDownTo(st, stopIdx, startRev){
  let out = "";
  // "0 вместо пустот" — та же сетка, что и у прямой сквозной (см. concatRowsDownTo); разворачивается
  // при этом уже РАЗЛОЖЕННАЯ ПО СЕТКЕ строка, иначе нули оказались бы не с той стороны.
  const g = st.padZero ? concatGridBounds(st, stopIdx) : null;
  for (let i = 0; i <= stopIdx; i++){
    const s = g ? concatRowPadded(st, i, g) : getRowBits(st, i);
    if (!s.length) continue;
    // startRev — ПРАВАЯ змейка (запрос пользователя): первая строка читается СПРАВА, вторая
    // слева, третья снова справа. Без него всё как было — первая слева.
    out += ((i % 2 === 1) !== !!startRev) ? reverseStr(s) : s;
  }
  return out;
}

/* Вертикальная склейка строк 0..stopIdx: читаются ПО СТОЛБЦАМ (а не по строкам, как
   concatRowsDownTo) — для каждого столбца сверху вниз собираются реальные символы тех строк,
   которые своей (со сдвигом выравнивания) шириной реально достают до этого столбца.
   dir "right": столбцы слева направо (0..maxLen-1). dir "left": столбцы справа налево.
   Идём от КРАЙНЕГО столбца (по направлению dir) и останавливаемся на первом же столбце, в
   котором нет битов НИ В ОДНОЙ участвующей строке — то, что лежит за этой дыркой, в результат
   уже не входит (запрос пользователя). Раньше пустые столбцы просто пропускались и склейка
   продолжалась до конца занятого диапазона, подхватывая оторванные куски за дыркой.
   При "½"-выравниваниях столбцы перебираются в ПОЛОВИННОМ разрешении (шаг 0.5 колонки, позиция
   строки = 2*сдвиг, +1 у той, что сидит в "полу"-сетке — тот же приём, что в computeDiagOnesMask),
   и участвуют ВСЕ строки, а не только под-сетка stopIdx-строки: на экране биты двух под-сеток
   стоят в РАЗНЫХ полустолбцах, и обход слева направо честно берёт их по очереди.
   Пример из запроса пользователя: строки "1","1","11" при "Центр ½" стоят так — полустолбец 0.5
   занят двумя единицами верхних строк, полустолбцы 0 и 1 — единицами нижней; обход даёт
   1 + 11 + 1 = "1111". Раньше фильтр по под-сетке оставлял ОДНУ нижнюю строку и выдавал "11".
   Строка ЧУЖОЙ под-сетки в полустолбце не считается даже дыркой — её там нет вовсе, поэтому
   галка "0 вместо пустот" на неё не срабатывает (иначе результат распух бы нулями вдвое). */
/* ОБЩИЙ план поколоночного обхода — им пользуются ВСЕ три поколоночных режима (Верт., Змейка,
   Верт.-зигзаг). Вынесено из concatVerticalDownTo(), потому что Змейка раньше жила на своей
   копии этой логики и постепенно отстала от неё: считала сдвиг через alignShift() (под
   "⊙ Ось"/"ОсьБит" это не те столбцы, что на экране), начинала колонки жёстко с нуля (биты,
   уехавшие левее, терялись), фильтровала ½-выравнивания по под-сетке выделенной строки и не
   знала про обрыв на дырке. Теперь любая правка геометрии автоматически видна во всех трёх.

   Сдвиг берётся через rowShiftFor(), а не alignShift() — только она знает про текущий
   круговой/осевой сдвиг конкретной строки (axisOffsetMap/axisBitShiftMap), поэтому под
   "⊙ Ось"/"Ось 1.2"/"ОсьБит"/"ОсьБит ½" столбцы берутся те же, что реально видны на экране.
   Всё считается в ПОЛУСТОЛБЦАХ (×2), чтобы полушаг ½-выравниваний был обычным целым числом:
   при не-½ выравниваниях все строки садятся на чётные полустолбцы и шаг обхода 2 — то есть
   ровно прежнее поведение, колонка в колонку.
   Отсчёт колонок — от САМОЙ ЛЕВОЙ занятой, а не жёстко от нуля: у "Лесенка правая" и осевых
   режимов строка свободно уезжает левее нулевой колонки.
   cols всегда слева направо — разворачивает его уже сам режим.
   startIdx (необязательный, по умолчанию 0) — ВЕРХНЯЯ граница участка. Поколоночные режимы всегда
   идут от 1-й строки (startIdx=0) и его не передают; диагоналям он нужен, чтобы при МУЛЬТИ-
   выделении участвовали ровно выделенные строки — у них появляется настоящая верхняя граница, от
   которой диагональ отражается так же, как от нижней (см. diagStartIdx/diagPathCells). */
function vertColumnPlan(st, stopIdx, startIdx){
  const isHalfAlign = alignIsHalf(st.align);
  const fromIdx = startIdx || 0;
  let maxLen = 0;
  for (let i = fromIdx; i <= stopIdx; i++) { const s = getRowBits(st, i); if (s.length > maxLen) maxLen = s.length; }
  // Полусимвольный нудж считается от ТОГО ЖЕ maxLen, что и сам сдвиг (локального, по строкам
  // 0..stopIdx) — НЕ от общего nudgeRefMaxLen(), как в xorRowsFiltered.
  // Почему: тут нудж — это не метка группы, а РЕАЛЬНОЕ СЛАГАЕМОЕ позиции
  // (shift2x = 2*⌊(L−len)/2⌋ + нудж). При совпадении чётностей L и G это даёт ровно L−len, а вот
  // при РАЗНОЙ чётности строки разъезжаются в противоположные стороны: у строк с чётным (L−len)
  // позиция становится (L−len)+1, у строк с нечётным — (L−len)−1, то есть две подсетки меняются
  // местами и сдвигаются друг относительно друга на ЦЕЛУЮ колонку. На экране такого нет: render()
  // берёт один и тот же maxLen и для сдвига, и для нуджа. Именно это ломало диагонали на "строках
  // нечётной подсетки" (запрос пользователя) — достаточно было одной длинной строки НИЖЕ
  // выделенной, чтобы локальный maxLen сменил чётность относительно общего.
  // Для xorRowsFiltered общий maxLen по-прежнему правильный: там нудж используется ТОЛЬКО как
  // фильтр "в какой группе строка", а не как часть координаты (см. nudgeRefMaxLen()).
  // Абсолютное начало отсчёта роли не играет: колонки перебираются от minCol, а не от нуля,
  // поэтому от локального maxLen картинка отличается от экранной лишь общим сдвигом на константу.
  // У "Лесенка ½"/"Лесенка правая ½" нудж считается от НОМЕРА строки и от maxLen не зависит вообще
  // (см. hasHalfNudge) — их это не касается.
  const nudgeMax = maxLen;
  const parts = [];
  let minCol = Infinity, maxCol = -Infinity;
  for (let i = fromIdx; i <= stopIdx; i++) {
    const s = getRowBits(st, i);
    if (!s.length) continue;
    const shift2x = 2 * rowShiftFor(maxLen, i, s, st.align) + rowHalf2x(i, s, st.align, nudgeMax);
    // row — НОМЕР строки в таблице (а не порядковый номер в parts): пустые строки сюда не
    // попадают, но экранную линию они занимают, и диагональным режимам (concatDiagDownTo) шаг
    // наклона надо считать именно по номеру строки, иначе диагональ "перепрыгнет" пустую строку.
    parts.push({ s, shift2x, row: i });
    if (shift2x < minCol) minCol = shift2x;
    if (shift2x + 2 * (s.length - 1) > maxCol) maxCol = shift2x + 2 * (s.length - 1);
  }
  if (!parts.length) return null;
  const step = isHalfAlign ? 1 : 2;
  const cols = [];
  for (let c = minCol; c <= maxCol; c += step) cols.push(c);
  // Одиночный пустой ПОЛУстолбец при ½-выравниваниях — это НЕ дырка в картинке, а нормальное
  // чередование двух под-сеток: если все участвующие строки оказались в одной под-сетке, каждый
  // второй полустолбец пуст ПО ПОСТРОЕНИЮ (напр. "1" и "111" при "Центр ½", maxLen=3: обе в
  // чётной под-сетке, заняты 0/2/4, а 1 и 3 пусты всегда). Обрыв по такому полустолбцу срабатывал
  // сразу после первого столбца, причём в каждую сторону на своём месте — отсюда и совсем разные
  // "Верт. →" и "Верт. ←" (запрос пользователя "почему прав и лев вертик дают разные?").
  // Дыркой считаем пустой ЦЕЛЫЙ столбец = gapLimit подряд пустых полустолбцов.
  // half — то же самое isHalfAlign наружу: диагональным режимам нужен полушаг наклона (0.5
  // столбца на строку), а не целый, ровно как в computeDiagOnesMask ("1⤡1").
  // startIdx/stopIdx/minCol/maxCol — тоже для диагоналей: им нужно знать, где ВЕРХНЯЯ и НИЖНЯЯ
  // границы участка (там отскоки) и где кончается занятая область по горизонтали (за ней ход
  // обрывается).
  // stairs — картинка сама по себе наклонена (обе "Лесенки ½"). У диагоналей там свой ход:
  // "Центр ½" ходит по-старому, см. развилку в diagLinesFor().
  // stairs — картинка сама наклонена ступеньками (все четыре "Лесенки"): у диагоналей там свой ход,
  // см. развилку в diagLinesFor(). mirror — ступеньку держит ПРАВЫЙ край строк, а не левый
  // ("Лесенка правая"/"Лесенка правая ½", см. diagRowEdgeCol): оттуда и стартуют линии.
  const isStairs = st.align === "stairs" || st.align === "halfstairs" ||
                   st.align === "rstairs" || st.align === "rhalfstairs";
  return { parts, cols, gapLimit: isHalfAlign ? 2 : 1, half: isHalfAlign, startIdx: fromIdx, stopIdx,
    minCol, maxCol, stairs: isStairs,
    mirror: st.align === "rstairs" || st.align === "rhalfstairs" };
}

/* Есть ли в полустолбце c хоть один РЕАЛЬНЫЙ бит. Нечётная разность (d % 2) — строка сидит в
   другой полусетке, в этом полустолбце её нет вообще. */
function vertColHasBit(parts, c){
  for (const p of parts) {
    const d = c - p.shift2x;
    if (d >= 0 && d % 2 === 0 && d / 2 < p.s.length && p.s[d / 2] !== ".") return true;
  }
  return false;
}

/* Проход по ЛИНИЯМ (столбцам у Верт./Змейки, диагоналям у Диаг.) в УЖЕ заданном порядке с
   правилом обрыва: ведущие пустышки пропускаем, а дойдя до настоящей дырки (gapLimit подряд
   пустых линий) — останавливаемся. hasBit(key) — есть ли в линии хоть один реальный бит.
   Возвращает список линий, которые реально идут в результат. */
function walkLinesWithGap(keys, hasBit, gapLimit){
  const out = [];
  let started = false, emptyRun = 0;
  for (const k of keys) {
    if (!hasBit(k)) {
      // До первой занятой линии ещё не дошли — такие ведущие пустышки просто пропускаем.
      if (!started) continue;
      // Пустая ЦЕЛАЯ линия — КОНЕЦ склейки, а не повод пропустить её и собирать дальше
      // (запрос пользователя: идём от крайней линии и останавливаемся там, где битов уже нет).
      emptyRun++;
      if (emptyRun >= gapLimit) break;
      continue;
    }
    emptyRun = 0;
    started = true;
    out.push(k);
  }
  return out;
}

/* Тот же обход для поколоночных режимов (Верт./Змейка/Верт.-зигзаг) — просто walkLinesWithGap()
   с проверкой "есть ли бит в полустолбце". */
function vertWalkCols(cols, parts, gapLimit){
  return walkLinesWithGap(cols, c => vertColHasBit(parts, c), gapLimit);
}

/* Символы одного полустолбца: сверху вниз, а при reversed — снизу вверх (нужно Змейке). */
function vertColBits(st, parts, c, reversed){
  const order = reversed ? parts.slice().reverse() : parts;
  let out = "";
  for (const p of order) {
    const d = c - p.shift2x;
    // Чужая полусетка — этого полустолбца у строки нет вовсе, она тут не участвует и дыркой
    // не считается (иначе "0 вместо пустот" удваивал бы результат нулями).
    if (d % 2 !== 0) continue;
    const j = d / 2;
    // Пустое место ВНУТРИ засчитанного столбца (эта строка сюда не достаёт): по умолчанию не
    // пишем ничего, а при включённой галке — "0" (запрос пользователя: "сами пустоты не писать,
    // и писать там 0 — по включённой кнопке настройки").
    if (j >= 0 && j < p.s.length) { if (p.s[j] !== ".") out += p.s[j]; }
    else if (st.padZero) out += "0";
  }
  return out;
}

function concatVerticalDownTo(st, stopIdx, dir){
  const plan = vertColumnPlan(st, stopIdx);
  if (!plan) return "";
  const cols = dir === "left" ? plan.cols.slice().reverse() : plan.cols;
  let out = "";
  for (const c of vertWalkCols(cols, plan.parts, plan.gapLimit)) out += vertColBits(st, plan.parts, c, false);
  return out;
}

/* "Верт. зигзаг" — столбцы берутся ПОПЕРЕМЕННО С ДВУХ КРАЁВ навстречу друг другу: крайний слева,
   крайний справа, следующий слева, следующий справа... пока не сойдутся в середине (запрос
   пользователя: "сначала слева потом справа потом снова слева"). dir задаёт, с какого края
   начинать: "right" — первым идёт САМЫЙ ЛЕВЫЙ столбец, "left" — самый правый.
   Обрыв на дырке считается ОТДЕЛЬНО для каждой стороны — тем же vertWalkCols(), что и у Верт.:
   левый ход идёт слева до первой дырки, правый — справа до первой дырки. Если дырки нет, обе
   стороны покрывают все столбцы и встречаются в середине, поэтому уже взятые столбцы
   отсеиваются через seen — иначе середина попала бы в результат дважды. */
function concatVertZigzagDownTo(st, stopIdx, dir){
  const plan = vertColumnPlan(st, stopIdx);
  if (!plan) return "";
  const fromLeft = vertWalkCols(plan.cols, plan.parts, plan.gapLimit);
  const fromRight = vertWalkCols(plan.cols.slice().reverse(), plan.parts, plan.gapLimit);
  const seen = new Set();
  const order = [];
  let a = 0, b = 0, takeLeft = dir !== "left";
  while (a < fromLeft.length || b < fromRight.length) {
    if (takeLeft) {
      while (a < fromLeft.length && seen.has(fromLeft[a])) a++;
      if (a < fromLeft.length) { seen.add(fromLeft[a]); order.push(fromLeft[a]); a++; }
    } else {
      while (b < fromRight.length && seen.has(fromRight[b])) b++;
      if (b < fromRight.length) { seen.add(fromRight[b]); order.push(fromRight[b]); b++; }
    }
    takeLeft = !takeLeft;
  }
  let out = "";
  for (const c of order) out += vertColBits(st, plan.parts, c, false);
  return out;
}


/* "Змейка" — та же вертикальная склейка по столбцам, но направление обхода строк ВНУТРИ
   столбца чередуется через один столбец (то сверху вниз, то снизу вверх), как в змейке/
   бустрофедоне. dir — та же логика направления столбцов, что у concatVerticalDownTo.
   Сами столбцы считает общий vertColumnPlan() — раньше тут была своя копия геометрии, отставшая
   от Верт. (alignShift вместо rowShiftFor, колонки от нуля, фильтр ½-под-сеток, без обрыва на
   дырке); теперь Змейка отличается от Верт. РОВНО одним — разворотом порядка строк в каждом
   втором взятом столбце. */
function concatSnakeDownTo(st, stopIdx, dir){
  const plan = vertColumnPlan(st, stopIdx);
  if (!plan) return "";
  const cols = dir === "left" ? plan.cols.slice().reverse() : plan.cols;
  const walk = vertWalkCols(cols, plan.parts, plan.gapLimit);
  let out = "";
  // Чередование считается по номеру РЕАЛЬНО взятого столбца (walk), а не по индексу в общем
  // списке — иначе пропущенные ведущие пустышки сбивали бы чётность.
  walk.forEach((c, k) => { out += vertColBits(st, plan.parts, c, k % 2 === 1); });
  return out;
}

/* ===== "Диагонали" (режимы фон-поиска diagR/diagL) =====
   То же самое, что вертикальная склейка, только линия обхода не отвесная, а НАКЛОННАЯ: с каждой
   следующей строкой она смещается на ПОЛСТОЛБЦА вбок — ровно та же геометрия, по которой считается
   подсветка "1⤡1" (computeDiagOnesMask: dirStep=1 в ×2-единицах на ½-выравниваниях), так что
   зелёные диагональные единички на экране и есть то, что эти режимы собирают.
   РАБОТАЮТ НА ЛЮБОМ ВЫРАВНИВАНИИ (см. diagAlignOk): шаг наклона берётся из plan.half — полстолбца
   за строку на ½-выравниваниях, целый столбец на остальных.
   slant: +1 — диагональ идёт ВНИЗ-ВПРАВО (↘), −1 — ВНИЗ-ВЛЕВО (↙).
   dir: "right" — диагонали перебираются слева направо, "left" — справа налево. Диагональ
   опознаётся по своему полустолбцу НА СТРОКЕ 0 (intercept d), поэтому "левее/правее" — это
   положение её ВЕРХНЕГО конца.
   Внутри одной диагонали биты берутся В ПОРЯДКЕ ХОДА; чужая полусетка (нечётная разность) — не
   дырка, строки в этой диагонали просто нет, "0 вместо пустот" на неё не срабатывает (тот же довод,
   что в vertColBits). Обрыв на дырке — общий walkLinesWithGap() с тем же gapLimit, что у столбцов.

   ОТСКОК (запрос пользователя): дойдя до нижней строки участка, диагональ не заканчивается, а идёт
   ОБРАТНО ВВЕРХ — вертикальный ход меняется на противоположный, а горизонтальный остаётся прежним,
   как мяч от стенки. Точно так же ход отражается от ВЕРХНЕЙ границы участка и — главное — от КРАЯ
   САМИХ ДАННЫХ: если в следующей строке в этом столбце бита уже нет, ход разворачивается, не
   уходя в пустоту. Получается змейка, идущая внутри занятой области и всё время уходящая вбок. Ход кончается там, где столбец вышел за пределы занятой области (plan.minCol/maxCol):
   назад он туда уже не вернётся.
   ВЕРХНЯЯ ГРАНИЦА — 1-я строка, а при МУЛЬТИВЫДЕЛЕНИИ самая верхняя ВЫДЕЛЕННАЯ (см. diagStartIdx):
   выделено несколько строк — работают ровно они, как у "Xor 2"/"XOR-Все".
   Отсюда и число диагоналей: ход возвращается на верхнюю границу через каждые 2×(число строк
   участка) шагов, в тот же столбец плюс тот же период — значит РАЗНЫХ диагоналей ровно
   2×(число строк участка), всё остальное это они же, начатые с другого места.
   Якорных подводов к первому/последнему символу нижней строки БОЛЬШЕ НЕТ: подвод шёл по краю
   данных и на лесенке превращался в длинную линию вдоль всего левого края, заслоняя собой сам
   зигзаг (запрос пользователя). Ход теперь ровно то, что он проходит сам. */
/* Диагонали работают на ВСЕХ выравниваниях (запрос пользователя "теперь также можно для всех
   остальных"). Вся арифметика хода общая и от конкретного выравнивания не зависит: сдвиг каждой
   строки берётся через rowShiftFor(), которая знает про все режимы, а шаг наклона — из plan.half
   (полстолбца за строку на ½-выравниваниях, целый столбец на остальных). Даже на не-½
   выравниваниях это не то же самое, что поколоночные режимы: там линия отвесная, а тут наклонная.
   Функция оставлена как единая точка, где ограничение можно вернуть. */
function diagAlignOk(st){
  return true;
}

/* Верхняя граница участка для диагоналей: выделено НЕСКОЛЬКО строк — самая верхняя из них (тогда
   участок это ровно выделение), иначе 1-я строка таблицы. */
function diagStartIdx(st){
  return (st.selectedRows && st.selectedRows.size > 1) ? Math.min(...st.selectedRows) : 0;
}

/* Номер строки (относительно верхней границы) на шаге t хода с отскоками — "треугольная волна":
   0,1,…,span,span−1,…,1,0,1,… Период 2*span. t может быть и отрицательным (ход вошёл в картинку
   раньше, чем пересёк верхнюю границу) — отсюда нормализация остатка. */
function diagRowOffsetAt(t, span){
  if (span <= 0) return 0;
  const period = 2 * span;
  const u = ((t % period) + period) % period;
  return u <= span ? u : period - u;
}

/* Строки плана по номеру строки — диагональ идёт по ЯЧЕЙКАМ (строка+столбец), а не по списку строк
   подряд, поэтому нужен доступ "какая строка живёт под этим номером". Кэшируется прямо в плане. */
function diagPartsByRow(plan){
  if (!plan.byRow) {
    plan.byRow = new Map();
    for (const p of plan.parts) plan.byRow.set(p.row, p);
  }
  return plan.byRow;
}

/* Ячейки одной диагонали (с отскоками от обеих границ) в порядке хода: [{row, col2x}, ...].
   d — полустолбец хода в тот момент, когда он идёт по ВЕРХНЕЙ границе вниз (шаг t=0); по нему
   диагональ и опознаётся при переборе.
   Шаг t — переход на соседнюю строку: столбец на шаге t равен d + slant*dirStep*t, а строка —
   треугольная волна (diagRowOffsetAt). Границы по t берём прямо из занятой области по горизонтали,
   поэтому ход сам собой начинается там, где входит в картинку, и кончается там, где выходит. */
/* Есть ли в ячейке РЕАЛЬНЫЙ бит (не пустое место за концом строки и не пустая строка). */
function diagCellFilled(plan, row, col2x, bias){
  const at = diagCellAt(plan, { row, col2x, bias });
  return !!(at && at.j >= 0 && at.j < at.p.s.length);
}

/* ↘ НА ВЫРАВНИВАНИЯХ 1:1 — семейство ПО СТРОКАМ, а не по столбцам (запрос пользователя: "зигзаг
   начинается с конца каждой строки, вниз, влево до конца и наверх"). Одна линия на строку:
     1) от ПОСЛЕДНЕГО символа своей строки — ВНИЗ до нижней строки участка (столбец прижимается к
        реальным битам каждой строки, поэтому спуск идёт по краю данных);
     2) по НИЖНЕЙ строке ВЛЕВО до её первого символа;
     3) ВВЕРХ по этому левому краю до верха участка — буква замыкается.
   У ↙ семейство прежнее, по столбцам (см. diagPathCellsOrtho) — там ход "П" и он верный. */
function diagPathCellsOrthoRow(plan, row, slant){
  const byRow = diagPartsByRow(plan);
  const startPart = byRow.get(row);
  if (!startPart || !startPart.s.length) return [];
  const cells = [];
  const startCol = slant > 0 ? (startPart.shift2x + 2 * (startPart.s.length - 1)) : startPart.shift2x;
  const clamp = (p, c) => Math.min(p.shift2x + 2 * (p.s.length - 1), Math.max(p.shift2x, c));
  let lastRow = row;
  for (let r = row; r <= plan.stopIdx; r++) {
    const p = byRow.get(r);
    if (!p || !p.s.length) continue;
    cells.push({ row: r, col2x: clamp(p, startCol), bias: slant });
    lastRow = r;
  }
  const bottom = byRow.get(lastRow);
  let endCol = startCol;
  if (bottom && bottom.s.length) {
    const from = clamp(bottom, startCol);
    // По нижней строке — ВЛЕВО до её первого символа. Пробовали развернуть вправо — откачено по
    // запросу пользователя: у ↘ ход "∪" работал верно именно так.
    endCol = bottom.shift2x;
    for (let c = from - 2; c >= endCol; c -= 2) {
      cells.push({ row: lastRow, col2x: c, bias: slant });
    }
  }
  for (let r = lastRow - 1; r >= plan.startIdx; r--) {
    const p = byRow.get(r);
    if (!p || !p.s.length) continue;
    cells.push({ row: r, col2x: clamp(p, endCol), bias: slant });
  }
  return cells;
}

/* ХОД ДЛЯ ВЫРАВНИВАНИЙ 1:1 (⇤ / ↔ / ⇥ и прочие не-½) — ОРТОГОНАЛЬНЫЙ, без диагоналей (запрос
   пользователя: "пусть там по строкам и вертикалям ходят только, и также снизу вверх до каждой
   верхней 1 символа, потом вправо/влево до конца строки, вниз до выделения").
   Одна линия семейства = один стартовый столбец col. Два зеркальных варианта, каждый — буква из
   трёх плеч (вертикаль, горизонталь, вертикаль):
     ↙ (slant<0) — "П_": СНИЗУ ВВЕРХ по столбцу до верхнего символа → по этой ВЕРХНЕЙ строке ВЛЕВО
        до её первого символа (влево ход уходит ТОЛЬКО тут, по верху) → ВНИЗ по левому краю до
        нижней строки участка → и хвост по этой (выделенной) строке ВПРАВО до её последнего
        символа, но начиная ПРАВЕЕ верхнего плеча: под верхней горизонталью нижней быть не должно;
     ↘ (slant>0) — "П" ПЕРЕВЁРНУТАЯ, то есть "∪": СВЕРХУ ВНИЗ по столбцу до нижнего символа → по
        этой НИЖНЕЙ строке вправо до её последнего символа → ВВЕРХ по краю до верха участка.
   Отсюда и "нижняя строка всегда имеет горизонтальные биты" у ↘. Обратное плечо прижимается к
   реальным битам каждой строки, поэтому идёт по краю данных, а не проваливается в пустоту.
   На ½-выравниваниях всё по-прежнему считает diagPathCellsCenter() — там ход и должен быть
   диагональным. */
function diagPathCellsOrtho(plan, col, slant){
  const byRow = diagPartsByRow(plan);
  const cells = [];
  // ХОД ↘ (slant > 0) ИДЁТ ВЕРХ НОГАМИ ОТНОСИТЕЛЬНО ↙ (запрос пользователя): он спускается по
  // столбцу СВЕРХУ ВНИЗ, поэтому горизонтальный пробег приходится на НИЖНЮЮ достигнутую строку —
  // "нижняя строка у него всегда горизонтальные биты имеет". ↙ (slant < 0) — зеркально: снизу
  // вверх, горизонталь по верхней строке.
  const downFirst = slant > 0;
  let turnRow = -1;
  if (downFirst) {
    for (let r = plan.startIdx; r <= plan.stopIdx; r++) {
      if (!diagCellFilled(plan, r, col, slant)) break; // столбец кончился — ниже не идём
      cells.push({ row: r, col2x: col, bias: slant });
      turnRow = r;
    }
  } else {
    for (let r = plan.stopIdx; r >= plan.startIdx; r--) {
      if (!diagCellFilled(plan, r, col, slant)) break; // столбец кончился — выше не идём
      cells.push({ row: r, col2x: col, bias: slant });
      turnRow = r;
    }
  }
  if (turnRow < 0) return [];
  const turn = byRow.get(turnRow);
  if (!turn || !turn.s.length) return cells;
  // ВЛЕВО ХОД УХОДИТ ТОЛЬКО ПО ВЕРХУ (запрос пользователя): верхнее плечо у ↙ идёт ВЛЕВО до
  // первого символа своей строки, а всё остальное — спуск и хвост — только вправо. У ↘ (он
  // строится другой функцией, diagPathCellsOrthoRow) горизонталь по нижней строке идёт вправо.
  const endCol = downFirst ? (turn.shift2x + 2 * (turn.s.length - 1)) : turn.shift2x;
  const stepCol = downFirst ? 2 : -2;
  for (let c = col + stepCol; downFirst ? c <= endCol : c >= endCol; c += stepCol) {
    cells.push({ row: turnRow, col2x: c, bias: slant });
  }
  // ТРЕТЬЕ ПЛЕЧО — обратно по краю, замыкая букву: у ↙ это "П" (вверх → поперёк верхней строки →
  // ВНИЗ до низа участка), у ↘ — перевёрнутая "П", то есть "∪" (вниз → поперёк нижней строки →
  // ВВЕРХ до верха участка). Столбец прижимаем к реальным битам каждой строки, чтобы плечо шло по
  // краю данных, а не проваливалось в пустоту.
  const legFrom = downFirst ? turnRow - 1 : turnRow + 1;
  const legTo = downFirst ? plan.startIdx : plan.stopIdx;
  const legStep = downFirst ? -1 : 1;
  let lastRow = turnRow, lastCol = endCol;
  for (let r = legFrom; downFirst ? r >= legTo : r <= legTo; r += legStep) {
    const p = byRow.get(r);
    if (!p || !p.s.length) continue;
    const lo = p.shift2x, hi = p.shift2x + 2 * (p.s.length - 1);
    const c = Math.min(hi, Math.max(lo, endCol)); // прижимаем к краю данных этой строки
    cells.push({ row: r, col2x: c, bias: slant });
    lastRow = r; lastCol = c;
  }
  // ХВОСТ "_" — по нижней (выделенной) строке ВПРАВО до её последнего символа, но НАЧИНАЯ ПРАВЕЕ
  // ВЕРХНЕГО ГОРИЗОНТАЛЬНОГО ПЛЕЧА (запрос пользователя: "не должно быть нижней там, над которой
  // есть верхняя горизонталь"). Верхнее плечо занимает столбцы от начала своей строки до стартового
  // столбца col — значит хвост идёт со столбца правее col.
  if (!downFirst) {
    const bottom = byRow.get(lastRow);
    if (bottom && bottom.s.length) {
      const rightEnd = bottom.shift2x + 2 * (bottom.s.length - 1);
      for (let c = Math.max(lastCol, col) + 2; c <= rightEnd; c += 2) {
        cells.push({ row: lastRow, col2x: c, bias: slant });
      }
    }
  }
  return cells;
}

/* ХОД ДЛЯ "Центр ½" — ровно как в версии 0.452, до всех правок под лесенки (запрос пользователя
   "для центра ½ верни логику 0.452, а лесенки норм в 0.468"): семейство по ФАЗЕ входа сбоку, ход на
   всю глубину участка, якорные подводы к первому/последнему символу нижней строки с постоянным
   наклоном. Лесенки ходят своим ходом, см. diagPathCellsStairs(). */
function diagPathCellsCenter(plan, d, slant, dirStep){
  const span = plan.stopIdx - plan.startIdx;
  const k = slant * dirStep; // насколько столбец уходит вбок за один шаг
  // minCol ≤ d + k*t ≤ maxCol; при k<0 деление переворачивает неравенство.
  const a = (plan.minCol - d) / k, b = (plan.maxCol - d) / k;
  const tLo = Math.ceil(Math.min(a, b)), tHi = Math.floor(Math.max(a, b));
  if (tHi < tLo) return [];
  // ЗМЕЙКА ПО ДАННЫМ (запрос пользователя "должен быть зиг-заг, змейка; лишние те, что над M"):
  // ход отскакивает не только от границ участка, но и от КРАЯ САМИХ ДАННЫХ — если в следующей
  // строке в этом столбце бита уже нет (строка там кончилась), ход разворачивается по вертикали.
  // Поэтому в "треугольнике" строк вершины зигзага садятся на скошенное ребро, а не лезут выше,
  // в узкие верхние строки — те ячейки и были лишними.
  // Фаза d по-прежнему задаёт, с какого места ход входит в картинку (см. diagLinesFor).
  let row = plan.startIdx + diagRowOffsetAt(tLo, span);
  let vdir = diagRowOffsetAt(tLo + 1, span) >= diagRowOffsetAt(tLo, span) ? 1 : -1;
  let col = d + k * tLo;
  const cells = [];
  for (let t = tLo; t <= tHi; t++) {
    // bias — куда округлять, если линия прошла между битами (см. diagCellAt): по ходу движения.
    cells.push({ row, col2x: col, bias: slant });
    const nextCol = col + k;
    let nr = row + vdir;
    const blocked = nr < plan.startIdx || nr > plan.stopIdx || !diagCellFilled(plan, nr, nextCol, slant);
    if (blocked) {
      vdir = -vdir;
      const back = row + vdir;
      if (back >= plan.startIdx && back <= plan.stopIdx && diagCellFilled(plan, back, nextCol, slant)) nr = back;
      else if (diagCellFilled(plan, row, nextCol, slant)) nr = row; // обе стороны глухие — идём своей строкой
      else nr = Math.min(plan.stopIdx, Math.max(plan.startIdx, nr));
    }
    row = nr;
    col = nextCol;
  }
  // Обрезаем ход по РЕАЛЬНЫМ битам. Ведущие/хвостовые ячейки в пустоте (фаза входит в картинку
  // выше или ниже данных) сами по себе ничего не дают, но по ним строится подвод — и он лез бы
  // вверх по краю ВЫШЕ настоящего начала змейки, оставляя лишний бит над вершиной
  // (запрос пользователя "слева лишняя сверху над М").
  let lo = 0, hi = cells.length - 1;
  while (lo <= hi && !diagCellFilled(plan, cells[lo].row, cells[lo].col2x, slant)) lo++;
  while (hi >= lo && !diagCellFilled(plan, cells[hi].row, cells[hi].col2x, slant)) hi--;
  if (lo > hi) return [];
  return diagAnchorCells(plan, cells.slice(lo, hi + 1), slant, dirStep);
}

/* ХОД ДЛЯ ЛЕСЕНОК. waveSpan — АМПЛИТУДА зигзага в строках: сколько строк ход проходит в одну
   сторону, прежде чем отпрыгнуть обратно. Глубина ОТНОСИТЕЛЬНАЯ (считается от последнего разворота,
   а не от верхней границы участка): картинка на лесенке уходит вниз-вправо, и в неподвижной полосе
   строк ход упирался бы в пустоту и обрывался. Якорных подводов тут нет — на лесенке подвод шёл по
   краю данных и превращался в длинную линию вдоль всего левого края. */
/* ХОД ДЛЯ ЛЕСЕНОК. По вертикали разворачивается ТОЛЬКО НА ГРАНИЦАХ (запрос пользователя):
     вниз — до самой нижней строки участка (выделенной),
     вверх — пока не упрётся в верхнюю границу участка ИЛИ в край самих данных.
   Никаких разворотов по счётчику строк посреди картинки.
   Линии семейства различаются СТРОКОЙ СТАРТА: каждая начинается с ПЕРВОГО СИМВОЛА своей строки
   (#1 — верхней, #2 — следующей, и так до нижней), идёт СНАЧАЛА ВВЕРХ, потом вниз — и дальше
   зигзагом до конца картинки (запрос пользователя). */
/* Полустолбец КРАЯ строки, по которому идёт сама лесенка: у "Лесенка ½" это ПЕРВЫЙ символ строки
   (её левый край и есть ступенька), у "Лесенка правая ½" — ПОСЛЕДНИЙ (там ступеньку держит правый
   край, а левый свободно уезжает влево, см. alignShift). От него и стартуют линии, по нему же идёт
   подвод сверху — иначе на правой лесенке всё считалось бы от свободного края и шло мимо ступенек
   (запрос пользователя "теперь по смыслу так же для правой лесенки"). */
function diagRowEdgeCol(plan, p){
  return plan.mirror ? p.shift2x + 2 * (p.s.length - 1) : p.shift2x;
}

function diagPathCellsStairs(plan, startRow, slant, dirStep, reachBottom){
  const k = slant * dirStep; // насколько столбец уходит вбок за один шаг
  const start = diagPartsByRow(plan).get(startRow);
  if (!start) return [];
  const canGo = (r, c) => r >= plan.startIdx && r <= plan.stopIdx && diagCellFilled(plan, r, c, slant);
  let row = start.row, col = diagRowEdgeCol(plan, start); // крайний символ своей строки
  let vdir = -1; // сначала ВВЕРХ — до границы участка или края данных
  const cells = [];
  const maxSteps = Math.floor((plan.maxCol - plan.minCol) / dirStep) + 4;
  for (let n = 0; n < maxSteps; n++) {
    // bias — куда округлять, если линия прошла между битами (см. diagCellAt): по ходу движения.
    cells.push({ row, col2x: col, bias: slant });
    const nextCol = col + k;
    let want = vdir;
    if (vdir > 0 && row >= plan.stopIdx) want = -1; // низ достигнут — разворот вверх
    let nr = canGo(row + want, nextCol) ? row + want : null;
    if (nr === null) {
      const other = -want;                          // граница участка или край данных — разворот
      if (canGo(row + other, nextCol)) { want = other; nr = row + other; }
      else if (diagCellFilled(plan, row, nextCol, slant)) { nr = row; want = 0; } // своей строкой
      else break; // некуда шагнуть, не попав в пустоту — ход кончается ЗДЕСЬ, а не рвётся дальше
    }
    if (want !== 0) vdir = want;
    row = nr;
    col = nextCol;
  }
  // Обрезаем ход по РЕАЛЬНЫМ битам (ведущие/хвостовые ячейки в пустоте ничего не дают).
  let lo = 0, hi = cells.length - 1;
  while (lo <= hi && !diagCellFilled(plan, cells[lo].row, cells[lo].col2x, slant)) lo++;
  while (hi >= lo && !diagCellFilled(plan, cells[hi].row, cells[hi].col2x, slant)) hi--;
  if (lo > hi) return [];
  const body = diagTopLeadCells(plan, startRow, slant).concat(cells.slice(lo, hi + 1));
  // Ход мог кончиться выше нижней строки — там, где упёрся в край данных. Тогда доводим его вниз
  // (кроме первой, самой левой линии — запрос пользователя).
  if (!reachBottom || body[body.length - 1].row >= plan.stopIdx) return body;
  return body.concat(diagDescendToBottom(plan, body[body.length - 1], slant, dirStep));
}

/* ПОДВОД СВЕРХУ (запрос пользователя "ещё сверху вниз сначала до текущего начала"): перед самим
   ходом линия проходит крайние символы всех строк ВЫШЕ своей — от верхней границы участка вниз до
   строки старта. Идёт по краю, который держит саму лесенку (см. diagRowEdgeCol), и упирается ровно в ту
   ячейку, с которой ход и начинается — стык без разрыва. У линии #1 (старт на верхней строке)
   подвода нет вовсе. Пустые строки пропускаются. */
function diagTopLeadCells(plan, startRow, slant){
  const byRow = diagPartsByRow(plan);
  const out = [];
  for (let r = plan.startIdx; r < startRow; r++) {
    const p = byRow.get(r);
    if (p) out.push({ row: r, col2x: diagRowEdgeCol(plan, p), bias: slant });
  }
  return out;
}

/* Спуск от последней ячейки хода до нижней строки участка — по строке за шаг. Сначала пробуем
   соседнюю ячейку (по ходу, против хода, прямо вниз), а если ни одна не занята — берём БЛИЖАЙШИЙ
   бит следующей строки. Так спуск доходит до нижней строки ВСЕГДА, пока строки под ним не пустые
   (запрос пользователя "зигзаг всегда должен доходить до нижней — выделенной"): раньше он молча
   кончался там, где у соседей битов не оказалось, и до низа не добирался. Пустые строки просто
   пропускаются. */
function diagDescendToBottom(plan, fromCell, slant, dirStep){
  const byRow = diagPartsByRow(plan);
  const out = [];
  let row = fromCell.row, col = fromCell.col2x;
  while (row < plan.stopIdx) {
    const nr = row + 1;
    const p = byRow.get(nr);
    if (!p) { row = nr; continue; } // пустая строка — просто проходим её насквозь
    let picked = null;
    for (const c of [col + slant * dirStep, col - slant * dirStep, col]) {
      if (diagCellFilled(plan, nr, c, slant)) { picked = c; break; }
    }
    if (picked === null) {
      // Соседей нет — прижимаемся к ближайшему биту этой строки (её крайнему, если ход ушёл вбок).
      const j = Math.min(p.s.length - 1, Math.max(0, Math.round((col - p.shift2x) / 2)));
      picked = p.shift2x + 2 * j;
    }
    row = nr; col = picked;
    out.push({ row, col2x: col, bias: slant });
  }
  return out;
}

/* Нижняя строка участка (если она пустая — ближайшая непустая выше): её ПЕРВЫЙ символ — общее
   начало всех диагоналей, ПОСЛЕДНИЙ — общий конец (см. diagAnchorCells). */
function diagAnchorPart(plan){
  const byRow = diagPartsByRow(plan);
  for (let r = plan.stopIdx; r >= plan.startIdx; r--) { const p = byRow.get(r); if (p) return p; }
  return null;
}

/* ОБЩИЕ КОНЦЫ (запрос пользователя): каждая диагональ начинается с ПЕРВОГО символа нижней строки
   выделения, диагональю поднимается до своего нынешнего начала, дальше идёт как шла (зигзаг с
   отскоками), а дойдя до края — снова спускается по крайней диагонали до ПОСЛЕДНЕГО символа нижней
   строки. Так у всех строк результата #1,#2,… одни и те же первый и последний биты, а различается
   только середина.
   Оба подводящих отрезка — обычные диагонали с тем же наклоном и с тем же горизонтальным ходом,
   что у самой линии: у хода вправо подвод поднимается вверх-ВПРАВО от первого бита нижней строки,
   а спуск идёт вниз-ВПРАВО и приходит в её последний бит. На "Центр ½" это ровно рёбра треугольника
   строк — по ним и идут те биты, которых раньше не хватало.
   Строятся ОТ САМОГО ЯКОРЯ (подвод — вверх от первого символа; спуск считается вверх от последнего,
   а проходится сверху вниз), поэтому нужный бит стоит в начале/конце ТОЧНО, без подгонки.
   Ячейки за пределами занятой области пропускаются — подвод там просто упирается в край и выходит
   короче. Если ход и так начинается/кончается в якорном бите (а для одной из фаз это ровно так и
   есть — получается непрерывная "галочка" по двум рёбрам сразу), лишние ячейки не дублируются. */
function diagAnchorCells(plan, cells, slant, dirStep){
  const anchor = diagAnchorPart(plan);
  if (!anchor || !cells.length) return cells;
  const first = cells[0], last = cells[cells.length - 1];
  const byRow = diagPartsByRow(plan);
  const anchorLeft = anchor.shift2x;                            // первый символ нижней строки
  const anchorRight = anchor.shift2x + 2 * (anchor.s.length - 1); // последний символ нижней строки
  // ЯКОРЯ ЗЕРКАЛЯТСЯ ПО НАПРАВЛЕНИЮ ХОДА (запрос пользователя): зигзаг ВЛЕВО (↙) должен
  // начинаться с КРАЙНЕГО ПРАВОГО символа нижней строки, подниматься по правому краю и уже потом
  // идти вниз-влево, а заканчиваться слева. У хода вправо (↘) — всё зеркально, как и было.
  const aCol = slant > 0 ? anchorLeft : anchorRight;
  const bCol = slant > 0 ? anchorRight : anchorLeft;
  const lead = [];
  for (let r = anchor.row; r >= first.row; r--) {
    // ПОДНИМАЕТСЯ ВБОК ПО ХОДУ (+slant), а не против него: у хода вправо подвод идёт вверх-ВПРАВО,
    // у хода влево — вверх-ВЛЕВО от правого края.
    let c = aCol + slant * dirStep * (anchor.row - r);
    const p = byRow.get(r);
    if (!p || !p.s.length) continue;                            // строки тут нет вовсе — пропускаем
    // Как и у спуска: столбец ПРИЖИМАЕМ к реальным битам строки, чтобы подвод шёл по самому краю
    // данных, а не обрывался на узких строках треугольника.
    const cLo = p.shift2x, cHi = p.shift2x + 2 * (p.s.length - 1);
    if (c < cLo) c = cLo;
    if (c > cHi) c = cHi;
    if (r === first.row && c === first.col2x) break;            // уже стоим на начале хода — не дублируем
    lead.push({ row: r, col2x: c, bias: slant });
  }
  const tail = [];
  for (let r = last.row; r <= anchor.row; r++) {
    // Спуск тоже идёт ВБОК ПО ХОДУ: считаем от якоря вверх против хода (−slant), а проходим сверху
    // вниз — значит вниз он уходит вправо и приходит ровно в последний бит нижней строки.
    let c = bCol - slant * dirStep * (anchor.row - r);
    // ПОСЛЕДНИЙ ВИТОК ОБЯЗАТЕЛЬНО ДОВОДИТСЯ ДО ВЫДЕЛЕННОЙ СТРОКИ (запрос пользователя): раньше
    // строки, где диагональ спуска уходила за край занятой области, просто пропускались, и ход
    // обрывался, не дойдя до низа. Теперь в таких строках идём по КРАЙНЕМУ биту строки со стороны
    // хода — "по крайним битам вниз до выделения", — а не выпадаем из линии.
    const p = byRow.get(r);
    if (!p || !p.s.length) continue;                            // строки тут нет вовсе — пропускаем
    // Столбец ПРИЖИМАЕМ к реальным битам этой строки, а не пропускаем строку: диагональ спуска
    // почти всегда выходит за узкие строки (треугольник), и раньше такие строки просто выпадали —
    // ход обрывался, не дойдя до низа. С прижатием в КАЖДОЙ строке от места выхода и до выделенной
    // берётся крайний доступный бит, то есть спуск идёт по краю данных и всегда доходит.
    const cLo = p.shift2x, cHi = p.shift2x + 2 * (p.s.length - 1);
    if (c < cLo) c = cLo;
    if (c > cHi) c = cHi;
    if (r === last.row && c === last.col2x) continue;
    tail.push({ row: r, col2x: c, bias: slant });
  }
  return lead.concat(cells, tail);
}

/* Что стоит в ячейке: null — строки тут нет вовсе (пустая строка), иначе {p, j} — строка и индекс
   бита (j может быть и вне длины строки: тогда это "пустое место внутри линии", см. padZero в
   diagPathBits).
   ЧУЖАЯ ПОЛУСЕТКА (нечётная разность) — линия проходит ровно МЕЖДУ двумя битами строки. Раньше
   такая ячейка выбрасывалась, и ход терял каждую вторую строку: и склейка, и подсветка шли
   дырками (запрос пользователя "чтоб без разрывов было"). Теперь берётся СОСЕДНИЙ бит — тот, что
   ПО ХОДУ движения (cell.bias — знак горизонтального хода на этом участке линии; у подводящих
   отрезков он свой, они идут вбок в обратную сторону). Округление всегда в одну сторону, поэтому
   линия не виляет: на ½-выравнивании она получается лесенкой в один бит на две строки — ровно та
   непрерывная "галочка"/"M", что нарисована на скриншоте. */
function diagCellAt(plan, cell){
  const p = diagPartsByRow(plan).get(cell.row);
  if (!p) return null;
  const rel2x = cell.col2x - p.shift2x;
  if (rel2x % 2 === 0) return { p, j: rel2x / 2 };
  return { p, j: (rel2x + (cell.bias < 0 ? -1 : 1)) / 2 };
}

function diagPathHasBit(plan, cells){
  for (const cell of cells) {
    const at = diagCellAt(plan, cell);
    if (at && at.j >= 0 && at.j < at.p.s.length) return true;
  }
  return false;
}

function diagPathBits(st, plan, cells){
  let out = "";
  for (const cell of cells) {
    const at = diagCellAt(plan, cell);
    if (!at) continue;
    if (at.j >= 0 && at.j < at.p.s.length) { if (at.p.s[at.j] !== ".") out += at.p.s[at.j]; }
    else if (st.padZero) out += "0";
  }
  return out;
}

/* Какие именно диагонали реально идут в результат — В ПОРЯДКЕ ОБХОДА, вместе с их ячейками.
   Отдельно от склейки, потому что ровно этот же список нужен подсветке "⧅⧄ Диагонали склейки"
   (computeDiagFoldMask): она обязана рисовать ТЕ ЖЕ линии, что режим складывает, включая обрыв
   на дырке. */
function diagLinesFor(plan, slant, dir){
  const dirStep = plan.half ? 1 : 2; // наклон: полстолбца на строку (½-выравнивания) или целый
  const step = plan.half ? 1 : 2;
  const span = plan.stopIdx - plan.startIdx;
  const keys = [];
  if (plan.stairs) {
    // НА ЛЕСЕНКАХ ЗЕРКАЛЬНОГО НАКЛОНА НЕТ ВОВСЕ (запрос пользователя "лесенка левая диагональ
    // зеркальная — убрать вообще, так же у правой"). Лесенка сама наклонена в одну сторону, и
    // осмысленный ход только один: у "Лесенка ½" вниз-вправо (↘), у "Лесенка правая ½" вниз-влево
    // (↙). Противоположный шёл поперёк ступенек и ничего не значил. Кнопка этого режима на лесенке
    // гасится, см. .mode-na в render().
    if (slant !== (plan.mirror ? -1 : 1)) return { dirStep, lines: [] };
    // ЛЕСЕНКИ: по одному зигзагу на каждую ГЛУБИНУ хода (строку отскока) — #1 частит мелким зубцом,
    // #N разворачивается через всю глубину участка. Глубина относительная, полоса едет вместе с
    // данными (см. diagPathCellsStairs).
    // ПО ОДНОЙ ЛИНИИ НА СТРОКУ участка: каждая стартует с ПЕРВОГО СИМВОЛА своей строки и идёт
    // сначала вверх, потом вниз (см. diagPathCellsStairs). Доводка до нижней строки — всем, кроме
    // первой, самой левой.
    plan.parts.forEach((p, i) => {
      keys.push({ d: p.row, cells: diagPathCellsStairs(plan, p.row, slant, dirStep, i > 0) });
    });
  } else if (!plan.half) {
    // ВЫРАВНИВАНИЯ 1:1 (не-½) — ход больше НЕ диагональный: он идёт только ПО СТРОКАМ И ПО
    // ВЕРТИКАЛЯМ (запрос пользователя). Каждая линия: снизу вверх по своему столбцу до самой
    // верхней строки, где в этом столбце ещё есть бит, дальше по этой строке до её края в сторону
    // хода, и оттуда вниз до выделенной строки. См. diagPathCellsOrtho().
    if (slant > 0) {
      // ↘ — по одной линии НА КАЖДУЮ СТРОКУ, от её конца (см. diagPathCellsOrthoRow).
      plan.parts.forEach(p => { keys.push({ d: p.row, cells: diagPathCellsOrthoRow(plan, p.row, slant) }); });
    } else {
      // ↙ — семейство по СТОЛБЦАМ, ход "П" (см. diagPathCellsOrtho).
      for (let c = plan.minCol; c <= plan.maxCol; c += 2) {
        keys.push({ d: c, cells: diagPathCellsOrtho(plan, c, slant) });
      }
    }
  } else {
    // "Центр ½": как было раньше — семейство по ФАЗЕ входа. РАЗНЫХ диагоналей ровно 2*span: ход
    // возвращается на верхнюю границу через 2*span шагов, то есть d и d + 2*span*dirStep — это одна
    // и та же линия, просто начатая с другого места. Участок в одну строку — вырожденный случай.
    const count = span > 0 ? (2 * span * dirStep) / step : 1;
    for (let i = 0; i < count; i++) {
      const d = plan.minCol + i * step;
      keys.push({ d, cells: diagPathCellsCenter(plan, d, slant, dirStep) });
    }
  }
  const order = dir === "left" ? keys.slice().reverse() : keys;
  // Пустые ходы просто отбрасываем, а не обрываем на них перебор, как у столбцов (walkLinesWithGap):
  // зигзаг с отскоками пересекает участок целиком, и "дырка" посреди него — не край картинки, а
  // случайность; обрыв на ней молча съел бы все оставшиеся диагонали.
  return { dirStep, lines: order.filter(k => diagPathHasBit(plan, k.cells)) };
}

function concatDiagDownTo(st, stopIdx, slant, dir){
  if (!diagAlignOk(st)) return "";
  const plan = vertColumnPlan(st, stopIdx, diagStartIdx(st));
  if (!plan) return "";
  const { lines } = diagLinesFor(plan, slant, dir);
  let out = "";
  for (const line of lines) out += diagPathBits(st, plan, line.cells);
  return out;
}

/* Маска подсветки "⧅⧄ Диагонали склейки" (см. #bHighlightDiagFold): для каждой строки — Map
   "индекс бита → 0/1", где значение это ЧЁТНОСТЬ НОМЕРА ДИАГОНАЛИ в порядке обхода (чередование
   яркости, см. .hldf-alt в CSS). Красятся ВСЕ биты на линии, и "1", и "0" — это линия обхода, а не
   находка.
   Какие наклоны рисовать — берётся из ВКЛЮЧЁННЫХ режимов фон-поиска diagR/diagL (подсветка должна
   показывать ровно то, что сейчас считается); не включён ни один — рисуются оба, иначе кнопка
   выглядела бы сломанной. Диапазон строк — тот же, что у самой склейки: от 1-й до САМОЙ НИЖНЕЙ
   выделенной, а без выделения — вся таблица.
   Разделители строк (rowDividers) тут НЕ учитываются — сама склейка их тоже не знает (в отличие от
   computeDiagOnesMaskSectioned у "1⤡1"); появится посекционная склейка — сюда придёт то же самое. */
/* Разбор ключа выбранной строки-диагонали ("diagR#3", "diagL#49+") в диапазон номеров линий:
   {base, from, to} (from включительно, to исключительно, 0-based). "+"-хвост (см. DIAG_SPLIT_MAX)
   — это не одна линия, а все оставшиеся, поэтому to = Infinity. */
function parseDiagPick(key){
  if (!key) return null;
  const hash = key.indexOf("#");
  if (hash < 0) return null;
  const base = key.slice(0, hash);
  if (base !== "diagR" && base !== "diagL") return null;
  const rest = key.slice(hash + 1);
  const tail = rest.endsWith("+");
  const num = parseInt(tail ? rest.slice(0, -1) : rest, 10);
  if (!num || num < 1) return null;
  return { base, from: num - 1, to: tail ? Infinity : num };
}

/* ЦВЕТ ПО ПОРЯДКУ СБОРА. Одна и та же радуга (жёлтый → зелёный → голубой → сиреневый) красит и
   биты в таблице, и символы результата: что собрано ПЕРВЫМ — жёлтое, что последним — сиреневое.
   Так видно не только КАКИЕ биты берёт режим, но и В КАКОМ ПОРЯДКЕ, и одно с другим сходится по
   цвету (запрос пользователя "показать, что первое, что потом — цветом, и там и там"). */
function foldOrderColor(i, total){
  const t = total > 1 ? i / (total - 1) : 0;
  return "hsl(" + Math.round(55 + t * 245) + ",85%,58%)";
}

/* Режимы фон-поиска, у которых захват идёт ПО КОЛОНКАМ — их линию тоже можно выбрать кликом по
   строке в "Результате" и увидеть в таблице (см. computeVertPickMask). */
const VERT_PICK_MODES = ["vertR", "vertL", "snakeR", "snakeL", "vertZigR", "vertZigL"];

/* Столбцы поколоночного режима В ПОРЯДКЕ ОБХОДА — тот же порядок, что у concatVerticalDownTo()/
   concatSnakeDownTo()/concatVertZigzagDownTo(), только собранный отдельно: сами склейки трогать
   незачем, они отдают биты, а тут нужны номера столбцов. Любая правка порядка обхода должна идти
   и туда, и сюда. */
function vertPickColumns(plan, mode){
  const left = mode === "vertL" || mode === "snakeL" || mode === "vertZigL";
  if (mode === "vertZigR" || mode === "vertZigL") {
    const fromLeft = vertWalkCols(plan.cols, plan.parts, plan.gapLimit);
    const fromRight = vertWalkCols(plan.cols.slice().reverse(), plan.parts, plan.gapLimit);
    const seen = new Set(), order = [];
    let a = 0, b = 0, takeLeft = !left;
    while (a < fromLeft.length || b < fromRight.length) {
      if (takeLeft) {
        while (a < fromLeft.length && seen.has(fromLeft[a])) a++;
        if (a < fromLeft.length) { seen.add(fromLeft[a]); order.push(fromLeft[a]); a++; }
      } else {
        while (b < fromRight.length && seen.has(fromRight[b])) b++;
        if (b < fromRight.length) { seen.add(fromRight[b]); order.push(fromRight[b]); b++; }
      }
      takeLeft = !takeLeft;
    }
    return order;
  }
  const cols = left ? plan.cols.slice().reverse() : plan.cols;
  return vertWalkCols(cols, plan.parts, plan.gapLimit);
}

/* Маска "какие биты захватывает выбранный ПОКОЛОНОЧНЫЙ режим", в том же формате, что у
   computeDiagFoldMask: строка → Map(индекс бита → чётность номера столбца в обходе). Помечается
   bgStyle — render() рисует такую линию фоном (см. .hldf-bg). */
function computeVertPickMask(st, mode){
  const n = st.rows.length;
  if (!n) return null;
  const stopIdx = (st.selectedRows && st.selectedRows.size) ? Math.max(...st.selectedRows) : n - 1;
  const plan = vertColumnPlan(st, stopIdx);
  if (!plan) return null;
  const masks = new Array(n).fill(null);
  masks.bgStyle = true;
  // Значение маски — ПОРЯДКОВЫЙ НОМЕР бита в обходе (0 — первый собранный), см. foldOrderColor.
  let ord = 0;
  for (const c of vertPickColumns(plan, mode)) {
    for (const p of plan.parts) {
      const d = c - p.shift2x;
      if (d < 0 || d % 2 !== 0) continue;
      const j = d / 2;
      if (j >= p.s.length) continue;
      if (!masks[p.row]) masks[p.row] = new Map();
      if (!masks[p.row].has(j)) masks[p.row].set(j, ord++);
    }
  }
  masks.total = ord;
  return masks;
}

function computeDiagFoldMask(st){
  if (!diagAlignOk(st)) return null;
  const n = st.rows.length;
  if (!n) return null;
  const stopIdx = (st.selectedRows && st.selectedRows.size) ? Math.max(...st.selectedRows) : n - 1;
  const plan = vertColumnPlan(st, stopIdx, diagStartIdx(st));
  if (!plan) return null;
  // ВЫБРАНА ОДНА ДИАГОНАЛЬ кликом по её строке в "Результате" (см. обработчик #chainText) — рисуем
  // ТОЛЬКО её, независимо от кнопки "⧅⧄" (запрос пользователя: "выделить мышкой одну — только её и
  // покажет, а всем вместе не надо"). Кнопка остаётся тем, чем была: показать все линии разом.
  const pick = parseDiagPick(st.diagFoldPick);
  const modes = st.bgSearchModes || [];
  const want = [];
  if (pick) {
    want.push(pick.base === "diagR" ? { slant: 1, dir: "right" } : { slant: -1, dir: "left" });
  } else {
    if (modes.includes("diagR")) want.push({ slant: 1, dir: "right" });
    if (modes.includes("diagL")) want.push({ slant: -1, dir: "left" });
    if (!want.length) want.push({ slant: 1, dir: "right" }, { slant: -1, dir: "left" });
  }
  const masks = new Array(n).fill(null);
  // Значение маски — ПОРЯДКОВЫЙ НОМЕР бита в обходе (0 — первый), общий счётчик по всем линиям:
  // цвет показывает, что собрано раньше, а что позже (см. foldOrderColor).
  let seq = 0;
  for (const w of want) {
    const { lines } = diagLinesFor(plan, w.slant, w.dir);
    lines.forEach((line, ord) => {
      if (pick && (ord < pick.from || ord >= pick.to)) return;
      for (const cell of line.cells) {
        const at = diagCellAt(plan, cell);
        if (!at) continue;                       // строки тут нет — в результат ничего не идёт
        const filled = at.j >= 0 && at.j < at.p.s.length;
        // СЧЁТЧИК ИДЁТ РОВНО ПО СИМВОЛАМ РЕЗУЛЬТАТА (см. diagPathBits): пустое место внутри линии
        // даёт символ только при "0️⃣ 0 вместо пустот", а уже покрашенный бит, встреченный ходом
        // повторно, всё равно добавляет символ в результат. Без этого номера в таблице и позиции
        // в строке результата разъезжались, и радуга "что собрано раньше" не совпадала между
        // таблицей и «Результатом» (запрос пользователя "соответствие цвета").
        if (!filled) { if (st.padZero) seq++; continue; }
        if (!masks[cell.row]) masks[cell.row] = new Map();
        // Первый claim выигрывает — при обоих наклонах сразу (да и на двух плечах одной линии)
        // бит может попасть на несколько ходов, перекрашивать его туда-сюда смысла нет.
        if (!masks[cell.row].has(at.j)) masks[cell.row].set(at.j, seq);
        seq++;
      }
    });
  }
  masks.total = seq;
  return masks;
}

/* Потолок на число ОТДЕЛЬНЫХ строк-диагоналей в панели результата (см. diagSplitResults). Каждая
   такая строка — самостоятельный кольцевой поиск + свой набор span'ов в отрисовке, поэтому на
   длинных таблицах их сотни (диагоналей примерно 2×maxLen + число строк). Всё, что не влезло в
   потолок, не теряется — уходит одной последней строкой "хвост" (склейка оставшихся диагоналей). */
const DIAG_SPLIT_MAX = 48;

/* "Каждая диагональ отдельно": режим "Диаг." даёт не только общую
   склейку, но и ПО СТРОКЕ РЕЗУЛЬТАТА НА КАЖДУЮ ДИАГОНАЛЬ — в том же порядке, в каком они идут в
   склейку. Каждая ищется по паттерну самостоятельно (см. mkResult в computeBgSearchTarget), т.е.
   совпадение внутри ОДНОЙ диагонали тоже считается находкой — ради этого всё и затевалось.
   Ключ строки — "<режим>#<номер>" (нумерация с 1, в порядке обхода), подпись собирает bgModeLabel(). */
function diagSplitResults(st, stopIdx, slant, dir, modeKey){
  if (!diagAlignOk(st)) return [];
  const plan = vertColumnPlan(st, stopIdx, diagStartIdx(st));
  if (!plan) return [];
  const { lines } = diagLinesFor(plan, slant, dir);
  const bits = line => diagPathBits(st, plan, line.cells);
  const shown = Math.min(lines.length, DIAG_SPLIT_MAX);
  const out = [];
  for (let i = 0; i < shown; i++) out.push({ mode: modeKey + "#" + (i + 1), result: bits(lines[i]) });
  if (lines.length > shown) {
    // Хвост за потолком — одной строкой, чтобы ничего не пропало молча.
    let tail = "";
    for (let i = shown; i < lines.length; i++) tail += bits(lines[i]);
    out.push({ mode: modeKey + "#" + (shown + 1) + "+", result: tail });
  }
  return out;
}

/* Есть ли у строки s ДОПОЛНИТЕЛЬНЫЙ полусимвольный сдвиг (+0.5ch, см. halfShiftAttr в render()) —
   ТОЧНО ТО ЖЕ условие, что красит строку в render(): у "Лесенка ½" зависит от ЧЁТНОСТИ ДЛИНЫ
   самой строки, у "Центр ½" — от чётности остатка (maxLen − длина). Это и есть настоящий признак
   "в какую из двух под-сеток (целую/полу) строка садится на экране" — НЕ чётность индекса/номера
   строки (это была ошибка в первой версии этой функции: строки одинаковой длины ВСЕГДА в одной
   подсетке независимо от порядка, а строки разной длины могут попасть в одну ИЛИ в разные,
   строго по формуле ниже). */
/* Опорная ширина для hasHalfNudge — ВСЕГДА общий maxLen по ВСЕЙ таблице, а не по подмножеству
   участвующих строк. У "Центр ½" подсетка строки считается от чётности (maxLen − длина), и
   render() берёт maxLen по ВСЕМ st.rows, тогда как XOR/склейки строят локальную сетку только по
   строкам 0..stopIdx (или по выделенным). Если чётность локального и общего maxLen разная, ВСЕ
   строки разом переезжают в противоположную подсетку: сама разбивка на группы при этом
   сохраняется (взаимный сдвиг двух строк = (len_b − len_a)/2 и от maxLen не зависит), но метки
   "целая"/"полу" меняются местами — и xorRowsDownTo() отдаёт группы в чередование в обратном
   порядке, т.е. результат расходится с тем, что нарисовано на экране. Достаточно ОДНОЙ длинной
   строки НИЖЕ выделенной, чтобы порядок бит перевернулся. У "Лесенка ½"/"Лесенка правая ½"
   этого нет — там подсетка считается от НОМЕРА строки и от maxLen не зависит вообще. */
function nudgeRefMaxLen(st, rows){
  const src = (st && st.rows) ? st.rows : (rows || []);
  let m = 0;
  for (const s of src) if (s && s.length > m) m = s.length;
  return m;
}
function hasHalfNudge(s, maxLen, align, rowIdx){
  if (!s.length) return false;
  // "Лесенка ½"/"Лесенка правая ½" — от чётности НОМЕРА строки: у них и сам сдвиг считается от
  // номера (см. alignShift), поэтому в "полу"-сетку садятся именно нечётные строки. У "Центр ½"
  // по-прежнему от чётности остатка (maxLen − длина) — там сдвиг зависит от длины.
  // При группировке ступеней (см. stairsStepIdx) "нечётной" считается не строка, а СТУПЕНЬ —
  // иначе внутри одной ступени строки разъезжались бы на полсимвола друг относительно друга.
  return (align === "halfstairs" || align === "rhalfstairs")
    ? stairsUnits(align, rowIdx) % 2 !== 0
    : (maxLen - s.length) % 2 !== 0;
}

/* "ПОЛУСТОЛБЕЦ" БЫВАЕТ НЕ ТОЛЬКО У "½"-ВЫРАВНИВАНИЙ. У "Ось 1.2" (axis12) и "ОсьБит ½"
   (axisbit12) строка тоже стоит на ПОЛСИМВОЛА в сторону — render() вешает ей extraCh −= 0.5
   (см. isAxisBetween/isAxisBitBetween там же). Знак МИНУС (строка левее, чтобы ось пришлась в
   зазор), а условие не "чётность (maxLen−len)", а своё: у "Ось 1.2" сдвинуты ВСЕ незамороженные
   строки, у "ОсьБит ½" — строки с НЕЧЁТНЫМ числом полушаговых звеньев (см. axisBitHalfSteps).
   Раньше про этот полушаг знал только render(), а все расчёты КОЛОНОК (интерлив, XOR,
   поколоночные и диагональные режимы фон-поиска) считали осевые "½" обычными целочисленными
   выравниваниями: биты соседних строк складывались в ОДНУ колонку, хотя на экране стоят через
   полсимвола (запрос пользователя — "интерливинг, фон-поиск работает норм в центральном
   выравнивании, а тут не верно"). Функции ниже — единая точка правды для всех таких расчётов. */
function alignIsHalf(align){
  return align === "halfcenter" || align === "halfstairs" || align === "rhalfstairs" ||
         align === "axis12" || align === "axisbit12";
}
/* Полушаг строки в ПОЛУСТОЛБЦАХ (×2): +1 у "½"-выравниваний (строка правее на полсимвола),
   −1 у осевых "½" (левее — ровно как extraCh −= 0.5 в render()), 0 у остальных. */
function rowHalf2x(i, s, align, nudgeMax){
  if (!s || !s.length) return 0;
  // "Ось 1.2": замороженные строки (без пары «1»→«0» при включённой галке ⊙) стоят обычным
  // "По центру" и полушага не имеют — та же развилка, что в rowShiftFor()/render().
  if (align === "axis12") return (st.axisSnap && !rowHasOneZeroPair(s)) ? 0 : -1;
  if (align === "axisbit12") return (axisBitHalfSteps(i) % 2 === 1) ? -1 : 0;
  return (align === "halfcenter" || align === "halfstairs" || align === "rhalfstairs")
    ? (hasHalfNudge(s, nudgeMax, align, i) ? 1 : 0)
    : 0;
}
/* Выравнивания, где сдвиг строки НЕ определяется одними её длинами: номер строки у лесенок,
   осевые карты у "Оси"/"ОсьБит" (axisOffsetMap/axisBitShiftMap), полушаг у "½". Пару таких строк
   можно складывать только ПО СТОЛБЦАМ (xorRowsFiltered/interleavePairRows) — xorPair()/
   interleavePair() видят одни строки, без номеров и сдвигов, и годятся лишь для ⇤ / ↔ / ⇥. */
function alignNeedsColumnAware(align){
  return align !== "left" && align !== "center" && align !== "right";
}

/* ХОР строк 0..stopIdx, отфильтрованных предикатом wantNudge (true/false — см. hasHalfNudge) —
   null означает "без фильтра, все строки" (обычные выравнивания). Ширина результата — МАКСИМУМ
   "сдвиг+длина" среди участвующих строк (а не просто длина, как было раньше) — иначе у "Лесенки"
   биты, уехавшие сдвигом за пределы самой длинной строки, молча терялись (Uint8Array тихо
   игнорирует запись за границей). */
// rowIdxs (необязательный) — явный список индексов строк вместо "все 0..stopIdx" — запрос
// пользователя: "если выделено несколько строк то только они участвуют, а не все что выше" (см.
// computeBgSearchTarget() → xor2/xorAll, передаёт туда st.selectedRows при мульти-выделении).
// Под "⊙ Ось" сдвиг строки ЗАВИСИТ от её индекса (axisOffsetMap — текущее положение конкретной
// строки относительно оси), а не только от длины, как у обычных выравниваний — alignShift() без
// индекса строки этого не знает. Запрос пользователя ("XOR 2/XOR-Чёт должны собирать по
// столбцам, а не по номеру бита в строке") — XOR ЭТИХ строк должен идти по ВИЗУАЛЬНЫМ столбцам
// (с учётом реального текущего кругового сдвига каждой строки), не по их собственным локальным
// индексам символов.
function rowShiftFor(maxLen, i, s, align){
  if (align === "axis") return axisRowShift(maxLen, i, s.length);
  // "Ось 1.2" — при включённой галке "⊙ Ось: сдвиг только на «1»/между «1-0»" (st.axisSnap)
  // замороженные строки (без пары «1»→«0», см. rowHasOneZeroPair) ХОР-ятся как обычное "По центру"
  // (та же логика, что и в render()), остальные — по осевой геометрии. При выключенной галке
  // заморозки нет вообще — все строки по осевой геометрии.
  if (align === "axis12") return (!st.axisSnap || rowHasOneZeroPair(s)) ? axisRowShift(maxLen, i, s.length) : alignShift(maxLen, s.length, "center");
  // Без st.axisCenterOffset — он общий визуальный сдвиг картинки, не часть геометрии строки
  // (см. alignShift()).
  if (align === "axisbit" || align === "axisbit12") return resolveAxisBitShift(i);
  // i пробрасывается дальше — "Лесенкам" он нужен, они считают ступеньку от номера строки.
  // ВАЖНО: у лесенок ступенька берётся от ПОКАЗЫВАЕМОГО номера (rowLabel), а не от индекса массива.
  // Построения сверху сдвигают все индексы, и от индекса лесенка ломалась бы на каждой достройке:
  // настоящие строки уезжали бы по диагонали вместе с числом зеркал. От номера же настоящие строки
  // стоят где стояли, а построенные получают отрицательные ступеньки — то есть лесенка честно
  // продолжается диагональю ВВЕРХ (запрос пользователя: "достройка в лесенках — также лесенкой по
  // диагонали").
  // ЛЕСЕНКИ СЧИТАЮТ СТУПЕНЬКУ ОТ ИНДЕКСА СТРОКИ — как и было всегда, включая построенные сверху
  // (запрос пользователя, его же раскладка):
  //     000
  //     .00
  //     ..0
  //     ...      ← нулевая строка, пустая, но своё место в лесенке занимает
  //     ....1
  //     .....11
  //     ......111
  // То есть ступенька идёт непрерывной диагональю сверху донизу: у построений длины убывают, у
  // настоящих строк растут, а ступенька марширует вправо у всех подряд. Пробовал считать от НОМЕРА
  // строки (чтобы настоящие строки не ехали при достройке) — картинка получалась не та, поэтому
  // вернул как было.
  return alignShift(maxLen, s.length, align, i);
}
function xorRowsFiltered(rows, stopIdx, align, st, wantNudge, rowIdxs){
  const idxs = rowIdxs || Array.from({ length: stopIdx + 1 }, (_, i) => i);
  // Точка отсчёта выравнивания — СОБСТВЕННЫЕ длины строк, без показанных зеркал (см.
  // mirrorPadsOf): ровно так же считает и render(), иначе колонки результата разъедутся с
  // картинкой. Сами биты зеркал в XOR при этом идут (они часть строки), просто стоят СБОКУ.
  let maxLen = 0;
  for (const i of idxs){
    const s = st ? getRowBits(st, i) : rows[i];
    if (!s.length) continue;
    const m = st ? mirrorPadsOf(st, i) : { l: 0, r: 0 };
    const ownLen = s.length - m.l - m.r;
    if (ownLen > maxLen) maxLen = ownLen;
  }
  // ФИЛЬТР "в какой подсетке живёт строка" (wantNudge) по-прежнему считается от ОБЩЕЙ ширины
  // таблицы, как её видит render() — см. nudgeRefMaxLen(): вызывающий (см. "Xor 2" при "½") сам
  // берёт подсетку выделенной строки от того же общего maxLen, и мерить их надо одной линейкой.
  const nudgeMax = nudgeRefMaxLen(st, rows);
  const isHalfAlign = alignIsHalf(align);
  // ВСЁ СЧИТАЕТСЯ В ПОЛУСТОЛБЦАХ (×2) — ровно как в vertColumnPlan() у поколоночных режимов.
  // Раньше здесь были ЦЕЛЫЕ колонки, а полусимвольное смещение "½"-выравниваний в координату не
  // входило вовсе (оно работало только как метка подсетки) — из-за этого биты двух подсеток
  // складывались в ОДНУ колонку, а xorRowsDownTo() потом сшивал две половины простым чередованием
  // "целая-полу", не глядя, какая из них начинается левее. На "Центр ½" со строками 1 / 11 / 111
  // это давало 11101 вместо правильного 11011 (запрос пользователя). Теперь позиция бита — это
  // 2*сдвиг + полушаг, то есть настоящий полустолбец с экрана, и XOR идёт колонка в колонку.
  // ВАЖНО: полушаг-КООРДИНАТА берётся от ЛОКАЛЬНОГО maxLen — от того же, от которого считается сам
  // сдвиг (иначе строки разъезжаются, см. тот же разбор в vertColumnPlan). Смена точки отсчёта
  // сдвигает ВСЕ строки на одну и ту же константу, поэтому картинка относительно себя не меняется.
  const parts = [];
  let minCol = Infinity, maxCol = -Infinity, evens = 0, odds = 0;
  for (const i of idxs){
    const s = st ? getRowBits(st, i) : rows[i];
    if (!s.length) continue;
    // own — строка БЕЗ зеркал: от неё считаются и выравнивание, и подсетка ("½"), как на экране.
    const m = st ? mirrorPadsOf(st, i) : { l: 0, r: 0 };
    const own = (m.l || m.r) ? s.slice(m.l, s.length - m.r) : s;
    if (wantNudge !== null && hasHalfNudge(own, nudgeMax, align, i) !== wantNudge) continue;
    // Зеркало слева отодвигает НАЧАЛО строки влево на свою длину — сам сдвиг строки от него не
    // меняется (см. mirrorPadsOf).
    const shift2x = 2 * (rowShiftFor(maxLen, i, own, align) - m.l) + rowHalf2x(i, own, align, maxLen);
    parts.push({ s, shift2x });
    if (shift2x < minCol) minCol = shift2x;
    if (shift2x + 2 * (s.length - 1) > maxCol) maxCol = shift2x + 2 * (s.length - 1);
    if (shift2x & 1) odds++; else evens++;
  }
  if (!parts.length) return "";
  // Шаг обхода: обе подсетки заняты — идём по КАЖДОМУ полустолбцу (их биты и правда стоят через
  // полсимвола), все строки в одной — шаг целый, иначе каждый второй полустолбец пуст ПО
  // ПОСТРОЕНИЮ и результат распух бы нулями вдвое. У не-½ выравниваний все сдвиги чётные, шаг
  // всегда 2 — то есть ровно прежнее поведение, колонка в колонку.
  const step = (evens && odds) ? 1 : 2;
  // Начало отсчёта — min(0, самый левый занятый полустолбец): при неотрицательных сдвигах
  // (обычные выравнивания) origin=0 и результат прежний, ВКЛЮЧАЯ ведущие нули, а при
  // отрицательных (Лесенка правая, осевые режимы — строка уезжает левее нулевой колонки)
  // диапазон честно расширяется влево, и её биты не теряются (запрос пользователя — "когда
  // верхняя строка имеет биты, которых в выделенной нет, их надо учитывать").
  let startCol = Math.min(0, minCol);
  if (((startCol ^ minCol) & 1)) startCol += 1; // сетка держится чётности занятых полустолбцов
  let out = "";
  for (let c = startCol; c <= maxCol; c += step){
    let bit = 0, has = false;
    for (const p of parts){
      const d = c - p.shift2x;
      if (d < 0 || (d & 1) !== 0 || (d >> 1) >= p.s.length) continue;
      if (p.s[d >> 1] === ".") continue;
      has = true;
      if (p.s[d >> 1] === "1") bit ^= 1;
    }
    // ШАГ 1 (обе подсетки заняты) — ПУСТОЙ полустолбец в результат не идёт вовсе: там на экране
    // просто нет бита, и подставлять вместо него ноль нельзя. Пример пользователя, "Центр ½" с
    // зеркалом влево: строки "1" и "011" (зеркало у второй) стоят в полустолбцах 1 и −2/0/2, между
    // −2 и 0 бита нет ни у кого — правильный ответ 0111, а не 00111.
    // При шаге 2 (все строки в одной подсетке) пустая колонка внутри участка — настоящая дырка
    // картинки, и там ноль по-прежнему печатается: так же, как и ведущие нули от начала отсчёта
    // (см. startCol выше) — это прежнее поведение обычных выравниваний, его не трогаем.
    if (step === 1 && !has) continue;
    out += bit;
  }
  return out;
}

/* Интерлив ПАРЫ СТРОК по их настоящим экранным полустолбцам — только для "½"-выравниваний (см.
   xorRowsFiltered выше, геометрия ровно та же). Обычный interleavePair() читает обе строки с
   позиции 0 и хвост без пары отбрасывает — на "Центр ½" это давало 1111 вместо 11111 для строк
   11 / 111 (запрос пользователя): на экране их биты стоят через полсимвола и переплетаются ВСЕ,
   ни один не лишний. Обход слева направо, внутри одного полустолбца сначала верхняя строка,
   потом нижняя; пустые полустолбцы в переплетение ничего не дают. */
function interleavePairRows(st, aIdx, bIdx, align, N){
  const colAware = alignIsHalf(align) || align === "axis" || align === "axisbit";
  let top = getRowBits(st, aIdx);
  const bot = getRowBits(st, bIdx);
  // Зеркала — как и в xorRowsFiltered: биты идут в переплетение, но выравнивание считается по
  // СОБСТВЕННОЙ длине строки, а левое зеркало отодвигает её начало влево (см. mirrorPadsOf).
  const mTop = mirrorPadsOf(st, aIdx), mBot = mirrorPadsOf(st, bIdx);
  // "⧬+1 Бит слева при чётной разности" (st.interleavePadEven, чекбокс #cInterleavePadEven под
  // кнопкой "⧬ Интерлив"). При ЧЁТНОЙ разности СОБСТВЕННЫХ длин (зеркала не в счёт) обе строки
  // сидят в ОДНОЙ подсетке колонок: их биты стоят строго друг под другом, и переплетения не
  // выходит — получается склейка столбец в столбец. Один лишний бит слева переводит верхнюю
  // строку в соседнюю подсетку, и биты идут через один (запрос пользователя). Бит вставляется
  // ПОСЛЕ левого зеркала, то есть в саму строку, а не перед её зеркалом, — иначе съехали бы
  // отступы mTop.l. Сами данные строки не меняются: бит живёт только внутри этого расчёта.
  if (st.interleavePadEven && top.length && bot.length) {
    const lTop = top.length - mTop.l - mTop.r, lBot = bot.length - mBot.l - mBot.r;
    if (((lTop - lBot) % 2) === 0) top = top.slice(0, mTop.l) + "0" + top.slice(mTop.l);
  }
  // Блочный интерлив (N > 1, "Интерлив сквозной") живёт по своим правилам — его не трогаем.
  if (!colAware || (N && N > 1)) return interleavePair(top, bot, align, N);
  const maxLen = Math.max(top.length - mTop.l - mTop.r, bot.length - mBot.l - mBot.r);
  const parts = [];
  let minCol = Infinity, maxCol = -Infinity;
  for (const [i, s, m] of [[aIdx, top, mTop], [bIdx, bot, mBot]]){
    if (!s.length) continue;
    const own = (m.l || m.r) ? s.slice(m.l, s.length - m.r) : s;
    const shift2x = 2 * (rowShiftFor(maxLen, i, own, align) - m.l) + rowHalf2x(i, own, align, maxLen);
    parts.push({ s, shift2x });
    if (shift2x < minCol) minCol = shift2x;
    if (shift2x + 2 * (s.length - 1) > maxCol) maxCol = shift2x + 2 * (s.length - 1);
  }
  if (!parts.length) return "";
  let out = "";
  for (let c = minCol; c <= maxCol; c++){
    for (const p of parts){
      const d = c - p.shift2x;
      if (d >= 0 && (d & 1) === 0 && (d >> 1) < p.s.length && p.s[d >> 1] !== ".") out += p.s[d >> 1];
    }
  }
  return out;
}


/* Накопительный ХОР всех строк 0..stopIdx разом — ОДНИМ проходом по полустолбцам, на любом
   выравнивании (см. xorRowsFiltered: там и геометрия, и выбор шага 1/2).
   Раньше "½"-выравнивания шли особым путём: строки делились на "целую" и "полу" подсетки, каждая
   ХОР-илась сама с собой, а две половины сшивались чередованием, "целая" первой. Сшивка не
   смотрела, какая из половин начинается ЛЕВЕЕ на экране, и на строках 1 / 11 / 111 при "Центр ½"
   выдавала 11101 вместо 11011 (запрос пользователя). Позиция бита теперь считается сразу в
   полустолбцах, поэтому делить на группы и сшивать их не нужно вовсе. */
function xorRowsDownTo(rows, stopIdx, align, st, rowIdxs){
  return xorRowsFiltered(rows, stopIdx, align, st, null, rowIdxs);
}

/* Сквозная строка цепочки */
function buildChain(st, aIdx, bIdx){
  const part = [];
  for (let i = 0; i < st.rows.length; i++){
    if (!st.rows[i].length) continue;
    if (i === aIdx || i === bIdx || st.used[i]) part.push(i);
  }
  const map = [];
  let text = "";
  if (!part.length) return { text, map };

  if (!st.vertical){
    for (const r of part){
      const s = getRowBits(st, r);
      for (let p = 0; p < s.length; p++){ if (s[p] === ".") continue; text += s[p]; map.push({ r, p }); }
    }
    return { text, map };
  }

  let maxLen = 0;
  for (const r of part) {
    const s = getRowBits(st, r);
    if (s.length > maxLen) maxLen = s.length;
  }
  const shifts = part.map(r => alignShift(maxLen, getRowBits(st, r).length, st.align, r));
  const buf = [];
  for (let p = 0; p < maxLen; p++){
    for (let k = 0; k < part.length; k++){
      const r = part[k], s = getRowBits(st, r), j = p - shifts[k];
      if (j >= 0 && j < s.length){ if (s[j] !== "."){ buf.push(s[j]); map.push({ r, p: j }); } }
      else if (st.padZero){ buf.push("0"); map.push(null); }
    }
  }
  return { text: buf.join(""), map };
}

/* Оптимизированный высокоскоростной поиск паттернов */
function findMatch(st, chainText, bIdx){
  const len = chainText.length;
  if (!len) return null;
  
  // Оптимизация 1: Однократное выделение памяти под кольцевой буфер (native V8 engine optimization)
  // "🚫 Без кольца" (st.ringOff) — буфер равен самой цепочке, замыкания через край нет.
  const ringText = st.ringOff ? chainText : chainText + chainText.slice(0, len - 1);
  // Какие версии паттерна перебирать — по отдельному тумблеру на каждую (см. KINDS_MODES).
  // kind 0 (прямой) в списке всегда, порядок прежний: прямой → инверсия → реверс.
  const kindList = [0];
  if (kindsInvOn()) kindList.push(1);
  if (kindsRevOn()) kindList.push(2);

  for (let i = bIdx + 1; i < st.pats.length; i++){
    const p = st.pats[i];
    if (!p || !p.text || p.found) continue;

    // Оптимизация 2: Ленивое кэширование инверсий и реверсов внутри паттерна!
    // Мы не вызываем тяжелые функции invertBits и reverseStr на каждом шаге.
    // Ключ кэша — обе отсечки сразу (см. patBase): иначе при "⏮ Без посл." отдавались бы куски,
    // нарезанные по прежней настройке.
    const skKey = (st.skipFirst ? 1 : 0) + (st.skipLast ? 2 : 0);
    if (p.cachedSkip !== skKey) {
      const base = patBase(p.text);
      p.s0 = base;
      p.s1 = invertBits(base);
      p.s2 = reverseStr(base);
      p.cachedSkip = skKey;
    }

    if (p.s0.length < 1 || p.s0.length > len) continue;
    
    // Оптимизация 3: Быстрый поиск через нативный indexOf
    for (const kind of kindList){
      const tail = kind === 0 ? p.s0 : kind === 1 ? p.s1 : p.s2;
      const pos = ringText.indexOf(tail);
      if (pos >= 0 && pos < len) {
        return { idx: i, kind, pos, len: tail.length };
      }
    }
    
    if (st.nextOnly) break;
  }
  return null;
}
