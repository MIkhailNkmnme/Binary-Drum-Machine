/* Выравнивание "⊙ Ось" (st.align==="axis") — запрос пользователя: круговой сдвиг ◄/►Круг(Инв)
   в этом режиме двигает ТОЛЬКО картинку, не саму строку — st.rows НЕ мутируется вообще, символы
   строки НЕ переставляются местами (порядок всегда естественный, как в st.rows) — поиск/XOR/
   Тетрис по-прежнему видят строку как она есть "по-настоящему". Биты всей строки едут КУЧЕЙ,
   как единое целое, вправо и влево ОТНОСИТЕЛЬНО НЕПОДВИЖНОЙ оси (запрос пользователя: "10011" с
   осью на первом символе → "(1)0011", после сдвига та же строка "10011" может оказаться
   смещена так, что на оси окажется её 4-й символ → "100(1)1", или последний → "1001(1)" —
   сама строка не крутится, просто уезжает целиком левее/правее). axisOffsetMap: индекс строки ->
   какой ИНДЕКС строки (в её естественном порядке) сейчас стоит на оси; применяется ТОЛЬКО при
   рендере через axisRowShift() ниже (сдвигает всю строку целиком), в кэш не сохраняется. Куда
   именно шаг сдвига (shiftOneRowAxisAware) ставит этот индекс — см. её комментарий: по умолчанию
   на оси должна оказаться «1», «0» пропускается — управляется галкой "⊙ На оси только «1»". */
let axisOffsetMap = new Map();
function getAxisOffset(rowIdx, len){
  if (!len) return 0;
  const off = axisOffsetMap.get(rowIdx) || 0;
  return ((off % len) + len) % len;
}
/* "ОсьБит"/"ОсьБит ½" (data-val="axisbit"/"axisbit12") — ось НЕ фиксированный столбец, а строка
   НЕПОСРЕДСТВЕННО НАД текущей: Круг/Круг Инв двигают текущую строку так, чтобы хоть одна её «1»
   встала в тот же визуальный столбец, что хоть одна «1» строки выше ("½" — не сам бит, а зазор
   между «1» и «0», аналогично "Ось 1.2"). Положение строки БЕЗ явного клика пользователя ЗАВИСИТ
   ТОЛЬКО от строки НАД ней — запрос пользователя ("ось задаёт строка выше, нижние вообще не
   должны влиять"): первая строка (нет строки выше) стоит с нуля (как "По левому краю"), любая
   следующая — по умолчанию НА ТОМ ЖЕ столбце, что и строка над ней (пока сама не подвинута
   Кругом) — рекурсивный, но короткий подъём вверх по цепочке, ни maxLen, ни строки НИЖЕ в этом
   вообще не участвуют (в отличие от старой версии, где дефолт был "По центру" от ОБЩЕЙ ширины
   таблицы — из-за этого короткие строки тянуло к далёким длинным строкам в другом месте
   таблицы, запрос пользователя "биты ушли за пределы своих осей"/"почему смотришь на строки
   внизу — ось задаёт только строка выше"). Реальный поиск происходит только в момент клика, когда
   положение строки выше уже разрешено (явно из карты, либо тот же дефолт). rowIdx=0 или пустая
   строка выше — двигать не на что, Круг/Круг Инв для такой строки ничего не делают (тот же no-op,
   что у "Ось 1.2" при длине < 2). */
let axisBitShiftMap = new Map();
/* Текущее направление обхода для режима "↩ От края назад" (st.axisBitBounce) — своё у КАЖДОЙ
   строки, потому что пользователь жмёт одну и ту же кнопку Круга, а строка должна помнить, идёт
   она сейчас вперёд или уже отразилась от края и возвращается. */
let axisBitDirMap = new Map();
/* Следующее положение sh внутри допустимого диапазона [minSh..maxSh].
   По умолчанию — КОЛЬЦО: упёрлись в край, продолжаем с противоположного.
   При включённой "↩ От края назад" вместо перескока на другой конец РАЗВОРАЧИВАЕМ направление —
   строка идёт обратно до упора, там разворачивается снова и т.д. (запрос пользователя: "чтобы
   дойдя до края не переход по кольцу, а шаг назад до упора и снова вперёд"). */
function axisBitNextSh(r, sh, step, minSh, maxSh){
  if (maxSh <= minSh) return sh;
  const dir = axisBitDirMap.get(r) || 1;
  let next = sh + step * dir;
  if (next >= minSh && next <= maxSh) return next;
  if (st.axisBitBounce) {
    axisBitDirMap.set(r, -dir);
    next = sh - step * dir;
    return (next >= minSh && next <= maxSh) ? next : sh;
  }
  return next > maxSh ? minSh : maxSh;
}
function resolveAxisBitShift(rowIdx){
  if (axisBitShiftMap.has(rowIdx)) return axisBitShiftMap.get(rowIdx);
  if (rowIdx <= 0) return 0;
  const above = st.rows[rowIdx - 1];
  if (!above || !above.length) return 0;
  return resolveAxisBitShift(rowIdx - 1);
}
// Число ПОДРЯД идущих полушаговых звеньев "ОсьБит ½" до этой строки (0 — сама строка/цепочка
// прервана пустой строкой выше). НЕЧЁТНОЕ значение — строка получает визуальный сдвиг −0.5ch
// (см. isAxisBitBetween в render()) И при поиске совпадения (axisBitHasMatch) целочисленное
// условие столбца сдвинуто на +1 относительно строки выше; ЧЁТНОЕ — ни то, ни другое. БЕЗ этого
// чередования два подряд «минус пол-символа» гасят друг друга и полушаговая связь пропадает через
// одну строку — именно это поймал пользователь ("1 и 2 строки сдвинуты на пол бита, а третья
// ровно под 1цей второй и скачет сразу на целый бит").
function axisBitHalfSteps(rowIdx){
  if (rowIdx <= 0) return 0;
  const above = st.rows[rowIdx - 1];
  if (!above || !above.length) return 0;
  return 1 + axisBitHalfSteps(rowIdx - 1);
}
// requirePair — «ОсьБит ½»: столбец должен быть НАЧАЛОМ пары «1»→«0» в строке above, не просто
// «1» ("ОсьБит" обычный — requirePair=false). adj — целочисленная поправка столбца (0 или 1,
// чередуется по чётности axisBitHalfSteps текущей строки, см. её комментарий выше) — БЕЗ неё
// "ОсьБит ½" ломается через одну строку (см. там же).
function axisBitHasMatch(cur, curShift, above, aboveShift, requirePair, adj){
  for (let m = 0; m < above.length; m++){
    if (above[m] !== "1") continue;
    if (requirePair && above[m + 1] !== "0") continue;
    for (let k = 0; k < cur.length; k++) if (cur[k] === "1" && curShift + k === aboveShift + m + adj) return true;
  }
  return false;
}
/* Геометрия "⊙ Ось"/"Ось 1.2" — итоговая версия (запрос пользователя, несколько раундов правок):
   ось стоит на столбце dataMaxLen/2 — это середина ВИДИМОЙ области между #vsplit и #vsplit2, той
   же ширины dataMaxLen, что и у любого обычного выравнивания (видимая область начинается со
   столбца 0, у vsplit) — ПЛЮС ручной сдвиг st.axisCenterOffset (запрос пользователя — вернули
   ручку переноса центра, но теперь это перетаскиваемая граница #axisSplit НАД линейкой столбцов
   (видом как #vsplit/#vsplit2, но не наезжающая на сами биты), а не ползунок в панели настроек,
   см. makeAxisDrag()/updateAxisSplitPosition() в JS).
   Круговой сдвиг ЛЮБОЙ строки может увести её стартовый столбец (shift = axisCol − off) как
   ЛЕВЕЕ, так и ПРАВЕЕ видимой области — раньше это ОБРЕЗАЛОСЬ (blankRun не может напечатать
   отрицательный отступ) и длинная строка визуально "упиралась" в край, не имея куда сдвигаться
   дальше (запрос пользователя "они там тормозятся"). Теперь вместо обрезки — при shift<0 сама
   строка целиком уезжает ЛЕВЕЕ .bits через transform:translateX (см. leftOverflowAttr в render()),
   а не печатается нулевым отступом; уезжает СВОБОДНО, без ограничения. Чтобы вылезающий текст (в
   любую сторону) не был виден "поверх" соседних панелей паттернов, а прятался ЗА ними — .pat/.pat2
   непрозрачны (var(--bg)) И стоят выше .bits по z-index (см. CSS), независимо от порядка в DOM. */
function axisRowShift(dataMaxLen, rowIdx, len){
  if (!len) return 0;
  // st.axisCenterOffset тут больше НЕ прибавляется — он стал общим визуальным сдвигом всей
  // картинки (см. комментарий в alignShift() и render()/renderColHeader()), одинаковым для всех
  // выравниваний, а не частью посточной геометрии.
  return Math.floor(dataMaxLen / 2) - getAxisOffset(rowIdx, len);
}
/* "Ось 1.2" (st.align==="axis12") — есть ли у строки ХОТЬ ОДНА пара соседних битов «1»→«0»
   (ИМЕННО в этом порядке — «0»→«1» не считается, ЛИНЕЙНО, БЕЗ зацикливания через край строки —
   запрос пользователя: у «10101» пары «1»→«0» на стыке первого/последнего бита нет, зацикливание
   тут НЕ считается). Строки без такой пары двигать некуда и не на что вставать осью — см.
   render()/shiftOneRowAxisAware. */
function rowHasOneZeroPair(s){
  for (let k = 0; k < s.length - 1; k++) if (s[k] === "1" && s[k + 1] === "0") return true;
  return false;
}
/* Синхронный сдвиг флагов при обычном (без инверсии) круговом сдвиге строки — сама подсветка
   не трогается, просто едет вместе с битом на новое место. */
function rotateInvFlagsLeft(arr){ return arr.length <= 1 ? arr : arr.slice(1).concat([arr[0]]); }
function rotateInvFlagsRight(arr){ return arr.length <= 1 ? arr : [arr[arr.length - 1]].concat(arr.slice(0, -1)); }
/* То же самое, но у бита, переходящего границу, флаг ПЕРЕКЛЮЧАЕТСЯ (не сохраняется как есть) —
   ровно то же место в массиве, что и переворачиваемый символ в rotateStrLeftInv/rotateStrRightInv.
   Выход только на ПУСТОМ массиве — по той же причине, что и там: единственный бит строки длины 1
   границу пересекает, значит и его флаг обязан переключиться, иначе подсветка "перевёрнут" разошлась
   бы с реально перевёрнутым битом. */
function rotateInvFlagsLeftInv(arr){ return arr.length < 1 ? arr : arr.slice(1).concat([!arr[0]]); }
function rotateInvFlagsRightInv(arr){ return arr.length < 1 ? arr : [!arr[arr.length - 1]].concat(arr.slice(0, -1)); }
/* КАК КРУТИТСЯ ПОМЕТКА «НОВЫЙ» (v0.888, вопрос пользователя "а при сдвигах новые не сохраняет?").
   У invFlags четыре варианта поворота: Inv-версии переворачивают заезжающий через шов флаг, потому
   что "Круг Инв" заодно инвертирует сам бит. Пометке «новый» инвертировать нечего — бит остаётся
   ТЕМ ЖЕ САМЫМ битом, даже если его значение перевернулось, — поэтому обе Inv-версии сводятся к
   обычному повороту в ту же сторону. */
const NEW_BITS_ROT = new Map([
  [rotateInvFlagsLeft, rotateInvFlagsLeft],
  [rotateInvFlagsLeftInv, rotateInvFlagsLeft],
  [rotateInvFlagsRight, rotateInvFlagsRight],
  [rotateInvFlagsRightInv, rotateInvFlagsRight]
]);
/* ОДИН круговой поворот строки r ВМЕСТЕ со всеми её позиционными картами: сами биты, флаги
   «перевёрнутых» (invFlagsMap) и пометка «новых» (newBitsMap). Раньше первые две строчки были
   расписаны вручную примерно в семи местах shiftOneRowAxisAware(), а newBitsMap не двигался
   вовсе — после Круга цвет новых бит оставался на прежних ПОЗИЦИЯХ, то есть уезжал на чужие
   биты (а при смене длины строки пропадал совсем). */
function rotateRowWithFlags(r, realRotateFn, invFlagsRotateFn){
  const len = st.rows[r] ? st.rows[r].length : 0;
  if (!len) return;
  invFlagsMap.set(r, invFlagsRotateFn(getInvFlags(r, len)));
  const nb = newBitsMap.get(r);
  if (nb && nb.length === len) newBitsMap.set(r, (NEW_BITS_ROT.get(invFlagsRotateFn) || rotateInvFlagsLeft)(nb));
  st.rows[r] = realRotateFn(st.rows[r]);
}
/* Повернуть ТОЛЬКО пометку «новых бит» строки — для мест, где саму строку и invFlags крутят
   отдельно (Тетрис 2 / Тетрис-ось: там сперва считают результат поворота, а применять его или
   откатить решают уже потом). Снимок пометки для такого отката — newBitsSnap()/newBitsPut(). */
function rotateNewBitsRow(rowIdx, invFlagsRotateFn){
  const nb = newBitsMap.get(rowIdx);
  const len = st.rows[rowIdx] ? st.rows[rowIdx].length : 0;
  if (nb && nb.length === len) newBitsMap.set(rowIdx, (NEW_BITS_ROT.get(invFlagsRotateFn) || rotateInvFlagsLeft)(nb));
}
function newBitsSnap(rowIdx){ const nb = newBitsMap.get(rowIdx); return nb ? nb.slice() : null; }
function newBitsPut(rowIdx, snap){ if (snap) newBitsMap.set(rowIdx, snap.slice()); else newBitsMap.delete(rowIdx); }
