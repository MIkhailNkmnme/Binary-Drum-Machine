(function patchDomLookupForPanelsPopup(){
  const getById = Document.prototype.getElementById;
  const qs = Document.prototype.querySelector;
  const qsa = Document.prototype.querySelectorAll;
  const alive = () => (typeof panelsPopupWin !== "undefined") && panelsPopupWin && !panelsPopupWin.closed;
  document.getElementById = function(id){
    const el = getById.call(document, id);
    if (el || !alive()) return el;
    return getById.call(panelsPopupWin.document, id);
  };
  document.querySelector = function(sel){
    const el = qs.call(document, sel);
    if (el || !alive()) return el;
    return qs.call(panelsPopupWin.document, sel);
  };
  document.querySelectorAll = function(sel){
    const list = qsa.call(document, sel);
    if (!alive()) return list;
    const extra = qsa.call(panelsPopupWin.document, sel);
    if (!extra.length) return list;
    return Array.from(list).concat(Array.from(extra)); // массив: .forEach/.length/индексы те же
  };
})();

