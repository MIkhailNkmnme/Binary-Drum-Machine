/* Все варианты циклического сдвига строки, включая саму строку (индекс 0) — для "Подпаттерны
   сдвига" фон-поиска: напр. "110" -> ["110","101","011"]. */
function rotationsOf(s){
  const out = [];
  for (let i = 0; i < s.length; i++) out.push(s.slice(i) + s.slice(0, i));
  return out;
}

/* Циклический сдвиг строки ВПРАВО на d позиций (d нормализуется по модулю длины). */
function rotateRightBy(s, d) {
  const L = s.length;
  if (!L || L === 1) return s;
  const shift = ((d % L) + L) % L;
  if (shift === 0) return s;
  return s.slice(-shift) + s.slice(0, -shift);
}

/* Для режима "🔢 Выбор столбца": среди ВСЕХ круговых сдвигов строки s, которые ставят '1'
   на позицию localCol, выбирает тот, при котором СЛЕВА от localCol (в результирующей
   строке) окажется МИНИМУМ единиц; при равенстве — берётся НАИМЕНЬШИЙ сдвиг. Строка без
   единиц вообще — возвращает null (сдвигать нечего). */
function bestColumnShift(s, localCol) {
  const L = s.length;
  if (localCol < 0 || localCol >= L) return null;
  let best = null, bestLeftOnes = Infinity;
  for (let j = 0; j < L; j++) {
    if (s[j] !== '1') continue;
    const d = ((localCol - j) % L + L) % L;
    const rotated = rotateRightBy(s, d);
    let leftOnes = 0;
    for (let k = 0; k < localCol; k++) if (rotated[k] === '1') leftOnes++;
    if (leftOnes < bestLeftOnes || (leftOnes === bestLeftOnes && d < best)) {
      bestLeftOnes = leftOnes;
      best = d;
    }
  }
  return best;
}

/* Определение максимальной длины паттернов для хвостового буфера стыка */
