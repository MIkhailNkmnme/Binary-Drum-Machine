/* НОК/НОД — нужны, чтобы правильно посчитать общий период кругового сдвига НЕСКОЛЬКИХ строк
   разной длины разом (см. totalTurns в autoRun()). НОК растёт ОЧЕНЬ быстро (напр. НОК(1..70) —
   астрономическое число, за пределами точности чисел JS, Number.MAX_SAFE_INTEGER ~9×10^15) —
   LCM_SAFE_CAP защищает от переполнения/потери точности: если общий НОК превысил потолок,
   lcmSafe() возвращает null — вызывающий код (autoRun()) трактует это как "предел неизвестен",
   totalTurns=0 (то же самое "без ограничения", что было ДО этой фичи — крутится, пока не нажмут
   Стоп) — реальный пользы от точного циклического предела в десятки миллионов ходов всё равно
   нет, никто не будет ждать столько кликов. */
const LCM_SAFE_CAP = 10000000; // 10 млн ходов — уже практически "бесконечно" для UI
function gcdInt(a, b) { while (b) { [a, b] = [b, a % b]; } return a; }
function lcmInt(a, b) { return a / gcdInt(a, b) * b; }
function lcmSafe(a, b) {
  const r = lcmInt(a, b);
  return (r > LCM_SAFE_CAP || !Number.isSafeInteger(r)) ? null : r;
}
/* Общий период кругового сдвига НАБОРА строк idxs (НОК их длин, ×2 у Круг Инв) — используется и
   в autoRun(), и при ручных кликах ◄/►Круг/Круг Инв (см. afterShiftBgCheck ниже), чтобы счётчик
   "Вар: N/M" в шапке "Результата" был одинаково верным что в "Авто", что при ручных кликах. */
function computeShiftTotalTurns(idxs, isShiftInv){
  let total = 0;
  for (const i of idxs) {
    const len = st.rows[i] ? st.rows[i].length : 0;
    if (len === 0) continue;
    if (total === 0) { total = len; continue; }
    const next = lcmSafe(total, len);
    if (next === null) return 0; // НОК слишком большой — "предел неизвестен"
    total = next;
  }
  if (total > 0 && isShiftInv) total *= 2;
  return total;
}
